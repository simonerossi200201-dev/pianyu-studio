def _push_history(pdir: Path, item: dict[str, Any], action: str, src_path: Path) -> None:
    if not src_path or not src_path.is_file():
        return
    hist = list(item.get("history") or [])
    next_ver = (max((int(h.get("ver") or 0) for h in hist), default=0) + 1)
    iid = item["id"]
    h_rel = f"history/{iid}_v{next_ver}.png"
    h_dest = pdir / h_rel
    h_dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src_path, h_dest)
    hist.append({
        "ver": next_ver,
        "action": action,
        "file": h_rel,
        "at": time.strftime("%H:%M:%S"),
    })
    item["history"] = hist


# ---------------- YuNet 人脸检测与画质质检 (QC) ----------------

def _get_yunet():
    global _YUNET_DETECTOR
    with _YUNET_LOCK:
        if _YUNET_DETECTOR is not None:
            return _YUNET_DETECTOR
        for mp in YUNET_MODEL_PATHS:
            if mp.is_file():
                try:
                    _YUNET_DETECTOR = cv2.FaceDetectorYN.create(
                        str(mp), "", (320, 320), 0.6, 0.3, 5000
                    )
                    return _YUNET_DETECTOR
                except Exception:
                    pass
        return None


def detect_faces(img_path: Path) -> list[dict[str, float]]:
    """返回归一化人脸框列表: [{x, y, w, h, score}, ...]，坐标范围 0..1。"""
    cs = _core_studio()
    if cs and hasattr(cs, "detect_faces"):
        try:
            res = cs.detect_faces(img_path)
            if isinstance(res, list):
                return res
        except Exception:
            pass

    if not img_path or not Path(img_path).is_file():
        return []
    try:
        pil_im = PILImage.open(img_path).convert("RGB")
        W, H = pil_im.size
        if W < 16 or H < 16:
            return []
        bgr = cv2.cvtColor(np.array(pil_im), cv2.COLOR_RGB2BGR)
    except Exception:
        return []

    det = _get_yunet()
    faces_out: list[dict[str, float]] = []
    if det is not None:
        try:
            # 缩放到合理检测尺寸以提速并保证精度
            scale = min(1.0, 1024.0 / max(W, H))
            dw, dh = max(32, int(round(W * scale))), max(32, int(round(H * scale)))
            small = cv2.resize(bgr, (dw, dh), interpolation=cv2.INTER_AREA)
            with _YUNET_LOCK:
                det.setInputSize((dw, dh))
                _, faces = det.detect(small)
            if faces is not None:
                for row in faces:
                    fx, fy, fw, fh = float(row[0]) / dw, float(row[1]) / dh, float(row[2]) / dw, float(row[3]) / dh
                    score = float(row[-1])
                    if score >= 0.55 and fw > 0.02 and fh > 0.02:
                        faces_out.append({
                            "x": round(max(0.0, min(1.0, fx)), 4),
                            "y": round(max(0.0, min(1.0, fy)), 4),
                            "w": round(max(0.01, min(1.0, fw)), 4),
                            "h": round(max(0.01, min(1.0, fh)), 4),
                            "score": round(score, 3),
                        })
        except Exception:
            pass
    return faces_out


def evaluate_qc(img_path: Path, target_w: int = 0, target_h: int = 0,
                faces: list[dict[str, float]] | None = None,
                typography: dict[str, Any] | None = None) -> dict[str, Any]:
    """画质与人脸防遮挡核验：清晰度(Laplacian)、曝光、分辨率、文字遮挡人脸检测。"""
    if not img_path or not Path(img_path).is_file():
        return {"sharpness": 0.0, "brightness": 0.0, "face_safe": True, "passed": False, "warnings": ["文件不存在"]}
    try:
        pil_im = PILImage.open(img_path).convert("RGB")
        W, H = pil_im.size
        gray = cv2.cvtColor(np.array(pil_im), cv2.COLOR_RGB2GRAY)
        sharp = float(cv2.Laplacian(gray, cv2.CV_64F).var())
        bright = float(gray.mean())
    except Exception as e:
        return {"sharpness": 0.0, "brightness": 0.0, "face_safe": True, "passed": False, "warnings": [str(e)]}

    warnings: list[str] = []
    if sharp < 35.0:
        warnings.append(f"画面偏模糊 (清晰度 {sharp:.0f})")
    if bright < 22.0:
        warnings.append("画面过暗")
    elif bright > 242.0:
        warnings.append("画面过曝")
    if min(W, H) < 512:
        warnings.append(f"分辨率偏低 ({W}×{H})")

    face_safe = True
    if faces and typography and typography.get("enabled"):
        has_title = bool(str(typography.get("title") or "").strip() or str(typography.get("subtitle") or "").strip())
        if has_title and not typography.get("depth_text"):
            ty = float(typography.get("title_y", 0.14))
            # 标题区大约占 ty-0.06 .. ty+0.12
            t_top, t_bot = max(0.0, ty - 0.06), min(1.0, ty + 0.12)
            for fc in faces:
                fy1, fy2 = float(fc["y"]), float(fc["y"]) + float(fc["h"])
                overlap = min(t_bot, fy2) - max(t_top, fy1)
                if overlap > 0.03:
                    face_safe = False
                    warnings.append("文字可能遮挡人物面部")
                    break

    return {
        "width": W,
        "height": H,
        "sharpness": round(sharp, 1),
        "brightness": round(bright, 1),
        "face_safe": face_safe,
        "passed": len(warnings) == 0,
        "warnings": warnings,
    }


