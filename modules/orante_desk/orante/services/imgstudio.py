def resolve_project_dir(tid: str | None = None, custom_dir: str | None = None) -> tuple[Path, dict | None]:
    """根据任务 ID 或默认工作区解析制图工坊工程目录。返回 (project_dir, task_dict_or_None)。"""
    if custom_dir and str(custom_dir).strip():
        d = Path(str(custom_dir).strip())
        d.mkdir(parents=True, exist_ok=True)
        return d, None
    tid = (tid or "").strip()
    if tid:
        try:
            t = taskmod.get(tid)
            tdir = t.get("dir")
            if tdir:
                pdir = Path(tdir) / "image_studio"
                pdir.mkdir(parents=True, exist_ok=True)
                return pdir, t
            # 任务还没建 dir 时放在 workspace/image_studio/<tid>
            ws = Path(config.get("workspace.dir") or paths.DEFAULT_WORKSPACE)
            pdir = ws / "image_studio" / tid
            pdir.mkdir(parents=True, exist_ok=True)
            return pdir, t
        except Exception:
            pass
    return _default_studio_dir(), None


def _ensure_subdirs(pdir: Path) -> None:
    for sub in ("raw", "composed", "matted", "masks", "history"):
        (pdir / sub).mkdir(parents=True, exist_ok=True)


def list_stickers() -> list[dict[str, str]]:
    out: list[dict[str, str]] = []
    seen: set[str] = set()
    for sdir in STICKER_DIRS:
        if not sdir.is_dir():
            continue
        for p in sorted(sdir.iterdir()):
            if p.is_file() and p.suffix.lower() in (".png", ".webp", ".jpg"):
                sp = str(p.resolve())
                if sp not in seen:
                    seen.add(sp)
                    out.append({"name": p.name, "path": sp})
    return out


def _default_sticker_path() -> str:
    st = list_stickers()
    return st[0]["path"] if st else ""


def load_project(pdir: Path) -> dict[str, Any]:
    _ensure_subdirs(pdir)
    fp = pdir / PROJECT_FILE
    with _LOCK:
        if fp.is_file():
            try:
                data = json.loads(fp.read_text(encoding="utf-8"))
                if isinstance(data, dict):
                    data.setdefault("version", 1)
                    data.setdefault("project_dir", str(pdir))
                    data.setdefault("default_typography", dict(DEFAULT_TYPOGRAPHY))
                    data.setdefault("items", [])
                    return data
            except Exception:
                pass
        def_typo = dict(DEFAULT_TYPOGRAPHY)
        if not def_typo.get("sticker_path"):
            def_typo["sticker_path"] = _default_sticker_path()
        data = {
            "version": 1,
            "project_dir": str(pdir),
            "created_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
            "default_typography": def_typo,
            "items": [],
        }
        save_project(pdir, data)
        return data


def save_project(pdir: Path, data: dict[str, Any]) -> None:
    _ensure_subdirs(pdir)
    fp = pdir / PROJECT_FILE
    data["project_dir"] = str(pdir)
    data["updated_at"] = time.strftime("%Y-%m-%dT%H:%M:%S")
    with _LOCK:
        fd, tmp = tempfile.mkstemp(dir=str(pdir), prefix=".ims-", suffix=".tmp")
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        os.replace(tmp, fp)


def _file_mtime_ms(p: Path | None) -> int:
    if not p or not p.is_file():
        return 0
    try:
        st = p.stat()
        return int(getattr(st, "st_mtime_ns", int(st.st_mtime * 1e9)) // 1_000_000)
    except OSError:
        return 0


def _decorate_item(pdir: Path, item: dict[str, Any], tid: str = "") -> dict[str, Any]:
    out = dict(item)
    iid = out.get("id") or ""
    raw_rel = out.get("raw_file") or ""
    comp_rel = out.get("composed_file") or ""
    mat_rel = out.get("matted_file") or ""

    raw_p = (pdir / raw_rel) if raw_rel else None
    comp_p = (pdir / comp_rel) if comp_rel else None
    mat_p = (pdir / mat_rel) if mat_rel else None

    raw_ok = bool(raw_p and raw_p.is_file())
    comp_ok = bool(comp_p and comp_p.is_file())
    mat_ok = bool(mat_p and mat_p.is_file())

    out["raw_exists"] = raw_ok
    out["composed_exists"] = comp_ok
    out["matted_exists"] = mat_ok
    out["raw_mtime"] = _file_mtime_ms(raw_p) if raw_ok else 0
    out["composed_mtime"] = _file_mtime_ms(comp_p) if comp_ok else 0
    out["matted_mtime"] = _file_mtime_ms(mat_p) if mat_ok else 0

    q_tid = f"tid={tid}&" if tid else ""
    out["raw_url"] = f"/media/imgstudio/raw/{iid}?{q_tid}v={out['raw_mtime']}" if raw_ok else ""
    out["composed_url"] = (
        f"/media/imgstudio/composed/{iid}?{q_tid}v={out['composed_mtime']}"
        if comp_ok else out["raw_url"]
    )
    out["matted_url"] = f"/media/imgstudio/matted/{iid}?{q_tid}v={out['matted_mtime']}" if mat_ok else ""

    # 装饰历史版本 URL
    hist_out = []
    for h in out.get("history") or []:
        hc = dict(h)
        hrel = hc.get("file") or ""
        hp = (pdir / hrel) if hrel else None
        hok = bool(hp and hp.is_file())
        hmtime = _file_mtime_ms(hp) if hok else 0
        ver = hc.get("ver", 1)
        hc["exists"] = hok
        hc["url"] = f"/media/imgstudio/history/{iid}?{q_tid}ver={ver}&v={hmtime}" if hok else ""
        hist_out.append(hc)
    out["history"] = hist_out
    return out


