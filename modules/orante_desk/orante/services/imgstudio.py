def compute_safe_layout(faces: list[dict[str, float]], typo: dict[str, Any]) -> dict[str, Any]:
    """根据 YuNet 检测到的人脸框，自动计算不遮挡人脸的标题/署名坐标。"""
    out = dict(typo)
    if not faces or not out.get("auto_avoid_face", True):
        return out

    # 找到最主要的人脸范围
    min_fy = min(float(f["y"]) for f in faces)
    max_fy = max(float(f["y"]) + float(f["h"]) for f in faces)

    ty = float(out.get("title_y", 0.14))
    t_top, t_bot = ty - 0.06, ty + 0.12
    # 如果当前标题纵向区域与人脸重叠
    if min(t_bot, max_fy) - max(t_top, min_fy) > 0.02:
        # 优先看上方空间够不够，否则放到人脸下方安全区
        if min_fy >= 0.24:
            out["title_y"] = round(max(0.08, min_fy - 0.14), 3)
        elif max_fy <= 0.72:
            out["title_y"] = round(min(0.82, max_fy + 0.08), 3)
        else:
            out["title_y"] = 0.08
    return out


def render_typography(pdir: Path, item: dict[str, Any], override_typo: dict[str, Any] | None = None) -> Path | None:
    """将标题、副标题、手机壳贴纸、AI 署名以及可选的前景穿插文字 (Depth Text) 渲染到 composed/<id>_final.png。"""
    raw_rel = item.get("raw_file") or ""
    raw_p = (pdir / raw_rel) if raw_rel else None
    if not raw_p or not raw_p.is_file():
        return None

    typo = dict(DEFAULT_TYPOGRAPHY)
    if isinstance(item.get("typography"), dict):
        typo.update(item["typography"])
    if isinstance(override_typo, dict):
        typo.update(override_typo)

    faces = item.get("faces")
    if faces is None:
        faces = detect_faces(raw_p)
        item["faces"] = faces

    if typo.get("auto_avoid_face", True):
        typo = compute_safe_layout(faces, typo)
    item["typography"] = typo

    comp_rel = f"composed/{item['id']}_final.png"
    comp_p = pdir / comp_rel
    comp_p.parent.mkdir(parents=True, exist_ok=True)

    # 如果未开启排版或没有任何文字/署名/贴纸，直接复制原图
    has_any = bool(
        typo.get("enabled", True) and (
            str(typo.get("title") or "").strip()
            or str(typo.get("subtitle") or "").strip()
            or str(typo.get("signature") or "").strip()
            or str(typo.get("sticker_path") or "").strip()
        )
    )
    if not has_any:
        shutil.copy2(raw_p, comp_p)
        item["composed_file"] = comp_rel
        item["qc"] = evaluate_qc(raw_p, item.get("width", 0), item.get("height", 0), faces, typo)
        return comp_p

    base_im = PILImage.open(raw_p).convert("RGBA")
    W, H = base_im.size
    preset_key = str(typo.get("preset") or "gold_cinema")
    preset = TYPO_PRESETS.get(preset_key) or TYPO_PRESETS["gold_cinema"]

    # 创建文字图层（用于支持 Depth Text 前景遮挡大字）
    text_layer = PILImage.new("RGBA", (W, H), (0, 0, 0, 0))
    draw = ImageDraw.Draw(text_layer)

    title_str = str(typo.get("title") or "").strip()
    sub_str = str(typo.get("subtitle") or "").strip()
    scale = max(0.4, min(2.5, float(typo.get("title_scale", 1.0) or 1.0)))

    if title_str or sub_str:
        tx = float(typo.get("title_x", 0.50)) * W
        ty = float(typo.get("title_y", 0.14)) * H
        base_t_size = int(min(W, H) * 0.068 * scale)
        base_s_size = int(min(W, H) * 0.038 * scale)
        font_t = _load_font(base_t_size, bold=True)
        font_s = _load_font(base_s_size, bold=False)
        sw = int(preset.get("stroke_width", 4))

        # 测量文字宽高
        t_bbox = draw.textbbox((0, 0), title_str, font=font_t, stroke_width=sw) if title_str else (0, 0, 0, 0)
        tw, th = t_bbox[2] - t_bbox[0], t_bbox[3] - t_bbox[1]
        s_bbox = draw.textbbox((0, 0), sub_str, font=font_s, stroke_width=max(2, sw - 1)) if sub_str else (0, 0, 0, 0)
        sfw, sfh = s_bbox[2] - s_bbox[0], s_bbox[3] - s_bbox[1]

        gap = int(min(W, H) * 0.015) if (title_str and sub_str) else 0
        total_w = max(tw, sfw)
        total_h = th + gap + sfh

        box_bg = preset.get("box_bg")
        if box_bg and total_w > 0:
            pad_x = int(min(W, H) * 0.032)
            pad_y = int(min(W, H) * 0.018)
            rx0 = int(tx - total_w / 2 - pad_x)
            ry0 = int(ty - pad_y)
            rx1 = int(tx + total_w / 2 + pad_x)
            ry1 = int(ty + total_h + pad_y)
            draw.rounded_rectangle([rx0, ry0, rx1, ry1], radius=14, fill=tuple(box_bg))

        cur_y = ty
        if title_str:
            draw.text(
                (int(tx - tw / 2), int(cur_y)),
                title_str,
                font=font_t,
                fill=tuple(preset["title_fill"]),
                stroke_width=sw,
                stroke_fill=tuple(preset["stroke_fill"]),
            )
            cur_y += th + gap
        if sub_str:
            draw.text(
                (int(tx - sfw / 2), int(cur_y)),
                sub_str,
                font=font_s,
                fill=tuple(preset["sub_fill"]),
                stroke_width=max(2, sw - 1),
                stroke_fill=tuple(preset["stroke_fill"]),
            )

    # 先把文字层合到底图上
    composed = PILImage.alpha_composite(base_im, text_layer)

    # 如果开启了 Depth Text（人物前景遮挡文字），自动确保有主体抠图图层并叠在标题层上方！
    if typo.get("depth_text") and (title_str or sub_str):
        mat_rel = item.get("matted_file") or ""
        mat_p = (pdir / mat_rel) if mat_rel else None
        if not (mat_p and mat_p.is_file()):
            try:
                mat_p = run_matte_single(pdir, item, mode="rmbg", bg_mode="transparent")
            except Exception:
                mat_p = None
        if mat_p and mat_p.is_file():
            try:
                fg_im = PILImage.open(mat_p).convert("RGBA")
                if fg_im.size != (W, H):
                    fg_im = fg_im.resize((W, H), PILImage.Resampling.LANCZOS)
                composed = PILImage.alpha_composite(composed, fg_im)
            except Exception:
                pass

    # 顶层装饰层：手机壳贴纸 + 署名文字（永远在最前景）
    fg_decor = PILImage.new("RGBA", (W, H), (0, 0, 0, 0))
    fg_draw = ImageDraw.Draw(fg_decor)

    sticker_path = str(typo.get("sticker_path") or "").strip()
    if sticker_path and os.path.isfile(sticker_path):
        try:
            st_im = PILImage.open(sticker_path).convert("RGBA")
            st_scale = max(0.05, min(0.8, float(typo.get("sticker_scale", 0.22) or 0.22)))
            target_sw = max(32, int(W * st_scale))
            target_sh = max(32, int(st_im.height * (target_sw / max(1, st_im.width))))
            st_im = st_im.resize((target_sw, target_sh), PILImage.Resampling.LANCZOS)
            sx = int(float(typo.get("sticker_x", 0.16)) * W - target_sw / 2)
            sy = int(float(typo.get("sticker_y", 0.85)) * H - target_sh / 2)
            sx = max(0, min(W - target_sw, sx))
            sy = max(0, min(H - target_sh, sy))
            fg_decor.alpha_composite(st_im, dest=(sx, sy))
        except Exception:
            pass

    sig_str = str(typo.get("signature") or "").strip()
    if sig_str:
        sig_size = max(16, int(min(W, H) * 0.028))
        font_sig = _load_font(sig_size, bold=True)
        sb = fg_draw.textbbox((0, 0), sig_str, font=font_sig, stroke_width=2)
        sgw, sgh = sb[2] - sb[0], sb[3] - sb[1]
        gx = int(float(typo.get("sig_x", 0.62)) * W - sgw / 2)
        gy = int(float(typo.get("sig_y", 0.90)) * H - sgh / 2)
        gx = max(8, min(W - sgw - 8, gx))
        gy = max(8, min(H - sgh - 8, gy))
        fg_draw.text(
            (gx, gy),
            sig_str,
            font=font_sig,
            fill=tuple(preset.get("sig_fill", (240, 235, 220, 215))),
            stroke_width=2,
            stroke_fill=(0, 0, 0, 210),
        )

    final_im = PILImage.alpha_composite(composed, fg_decor).convert("RGB")
    final_im.save(comp_p, format="PNG")
    item["composed_file"] = comp_rel
    item["qc"] = evaluate_qc(raw_p, item.get("width", W), item.get("height", H), faces, typo)
    return comp_p


# ---------------- 提示词解析与任务导入 ----------------

def parse_batch_prompts(text: str, aspects: list[str] | None = None,
                        count_per_prompt: int = 1,
                        default_typo: dict[str, Any] | None = None) -> list[dict[str, Any]]:
    """支持多行提示词、竖线分隔 `提示词 | 标题 | 副标题` 或 TSV `序号\\t提示词\\t标题\\t副标题`。"""
    aspects = [a for a in (aspects or ["9:16"]) if a in ASPECT_PRESETS] or ["9:16"]
    count = max(1, min(int(count_per_prompt or 1), 8))
    base_typo = dict(DEFAULT_TYPOGRAPHY)
    if isinstance(default_typo, dict):
        base_typo.update(default_typo)

    rows: list[tuple[str, str, str]] = []
    for raw_ln in (text or "").splitlines():
        ln = raw_ln.strip()
        if not ln or ln.startswith("#"):
            continue
        if "\t" in ln:
            parts = [p.strip() for p in ln.split("\t")]
            # 如果第一列是纯数字或 p01 序号，跳过第一列
            if len(parts) >= 2 and re.match(r"^(p?\d+|s?\d+)$", parts[0], re.I):
                parts = parts[1:]
            prompt = parts[0] if parts else ""
            title = parts[1] if len(parts) > 1 else ""
            sub = parts[2] if len(parts) > 2 else ""
        elif "|" in ln or "｜" in ln:
            parts = [p.strip() for p in re.split(r"[|｜]", ln)]
            prompt = parts[0] if parts else ""
            title = parts[1] if len(parts) > 1 else ""
            sub = parts[2] if len(parts) > 2 else ""
        else:
            prompt, title, sub = ln, "", ""
        if prompt:
            rows.append((prompt, title, sub))

    new_items: list[dict[str, Any]] = []
    for prompt, title, sub in rows:
        for asp in aspects:
            spec = ASPECT_PRESETS[asp]
            for c_idx in range(count):
                iid = f"im_{uuid.uuid4().hex[:8]}"
                it_typo = dict(base_typo)
                if title:
                    it_typo["title"] = title
                if sub:
                    it_typo["subtitle"] = sub
                new_items.append({
                    "id": iid,
                    "prompt": prompt,
                    "negative_prompt": "",
                    "aspect": asp,
                    "width": spec["w"],
                    "height": spec["h"],
                    "engine": "flux2",
                    "seed": int(time.time() * 1000) % 1000000 + len(new_items) * 17 + c_idx,
                    "status": "pending",
                    "review": "pending",
                    "rating": 0,
                    "raw_file": f"raw/{iid}.png",
                    "composed_file": f"composed/{iid}_final.png",
                    "matted_file": "",
                    "faces": [],
                    "typography": it_typo,
                    "qc": {"sharpness": 0.0, "brightness": 0.0, "face_safe": True, "passed": True, "warnings": []},
                    "history": [],
                    "created_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
                })
    return new_items


def add_prompts(tid: str | None, text: str, aspects: list[str] | None = None,
                count_per_prompt: int = 1, typography: dict[str, Any] | None = None) -> dict[str, Any]:
    pdir, _ = resolve_project_dir(tid)
    proj = load_project(pdir)
    if isinstance(typography, dict):
        proj["default_typography"] = {**(proj.get("default_typography") or DEFAULT_TYPOGRAPHY), **typography}
    added = parse_batch_prompts(text, aspects, count_per_prompt, proj.get("default_typography"))
    if not added:
        raise OranteError("没有解析到有效提示词", "每行输入一条生图提示词，支持『提示词 | 标题 | 副标题』格式。")
    proj.setdefault("items", []).extend(added)
    save_project(pdir, proj)
    return {"added": len(added), **get_state(tid)}


def import_from_task(tid: str, mode: str = "images") -> dict[str, Any]:
    """从当前 Orante 任务导入已有图片 (`mode="images"`) 或分镜提示词 (`mode="prompts"`)。"""
    tid = (tid or "").strip()
    if not tid:
        raise OranteError("请先在顶栏选择一个任务", "选择任务后才能导入该任务的分镜或图片。")
    t = taskmod.get(tid)
    tdir = Path(t["dir"]) if t.get("dir") else None
    pdir, _ = resolve_project_dir(tid)
    proj = load_project(pdir)
    def_typo = dict(proj.get("default_typography") or DEFAULT_TYPOGRAPHY)
    added_count = 0

    if mode == "prompts":
        lines: list[str] = []
        if tdir and (tdir / "manifest.json").is_file():
            m = Manifest.load(tdir)
            for im in (m.images or []):
                desc = str(im.get("desc") or "").strip()
                if desc:
                    lines.append(desc)
            if not lines:
                for sg in (m.segments or []):
                    txt = str(sg.get("shot") or sg.get("text") or "").strip()
                    if txt:
                        lines.append(txt)
        if not lines and str(t.get("copy") or "").strip():
            for ln in str(t.get("copy") or "").splitlines():
                if ln.strip():
                    lines.append(ln.strip())
        if not lines:
            raise OranteError("该任务还没有可导入的描述语或文案", "可以先在任务里准备图片或直接输入提示词。")
        new_items = parse_batch_prompts("\n".join(lines), ["9:16"], 1, def_typo)
        proj.setdefault("items", []).extend(new_items)
        save_project(pdir, proj)
        return {"added": len(new_items), **get_state(tid)}

    # mode == "images": 导入 task_dir/images 下的图片
    if not tdir or not (tdir / "images").is_dir():
        raise OranteError("该任务还没有准备图片目录", "先在「① 任务」面板点「准备」，或者用「导入本地图片文件夹」。")
    from . import images as imgmod
    files = imgmod.list_library_files(tdir / "images")
    if not files:
        raise OranteError("任务的 images 目录里没有图片", str(tdir / "images"))

    desc_by_file: dict[str, str] = {}
    if (tdir / "manifest.json").is_file():
        try:
            m = Manifest.load(tdir)
            for im in (m.images or []):
                rel = Path(im.get("file") or "").name
                desc_by_file[rel] = str(im.get("desc") or "")
        except Exception:
            pass

    for fp in files:
        iid = f"im_{uuid.uuid4().hex[:8]}"
        raw_rel = f"raw/{iid}.png"
        raw_dest = pdir / raw_rel
        pil_im = PILImage.open(fp).convert("RGB")
        W, H = pil_im.size
        pil_im.save(raw_dest, format="PNG")
        aspect = "9:16" if H >= W * 1.2 else ("16:9" if W >= H * 1.2 else "1:1")
        faces = detect_faces(raw_dest)
        item = {
            "id": iid,
            "prompt": desc_by_file.get(fp.name) or fp.stem,
            "negative_prompt": "",
            "aspect": aspect,
            "width": W,
            "height": H,
            "engine": "imported",
            "seed": 0,
            "status": "ready",
            "review": "pending",
            "rating": 0,
            "src_name": fp.name,
            "raw_file": raw_rel,
            "composed_file": f"composed/{iid}_final.png",
            "matted_file": "",
            "faces": faces,
            "typography": dict(def_typo),
            "qc": {},
            "history": [],
            "created_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
        }
        _push_history(pdir, item, f"导入 ({fp.name})", raw_dest)
        render_typography(pdir, item)
        proj.setdefault("items", []).append(item)
        added_count += 1

    save_project(pdir, proj)
    return {"added": added_count, **get_state(tid)}


