def resolve_media_file(kind: str, item_id: str, tid: str | None = None, ver: int | None = None) -> Path:
    pdir, _ = resolve_project_dir(tid)
    proj = load_project(pdir)
    item = next((x for x in (proj.get("items") or []) if x.get("id") == item_id), None)
    if not item:
        raise OranteError("找不到图片条目")
    if kind == "history" and ver is not None:
        h_entry = next((h for h in (item.get("history") or []) if int(h.get("ver") or 0) == int(ver)), None)
        if h_entry and (pdir / (h_entry.get("file") or "")).is_file():
            return (pdir / h_entry["file"]).resolve()
    if kind == "composed":
        cp = pdir / (item.get("composed_file") or "")
        if cp.is_file():
            return cp.resolve()
    if kind == "matted":
        mp = pdir / (item.get("matted_file") or "")
        if mp.is_file():
            return mp.resolve()
    rp = pdir / (item.get("raw_file") or "")
    if rp.is_file():
        return rp.resolve()
    raise OranteError("图片文件不存在")
