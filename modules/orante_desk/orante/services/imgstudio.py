# ---------------- Mode B: 单图精修 —— 局部重绘 (Inpaint) 与无痕擦除 (Erase) ----------------

def _decode_data_url_mask(mask_data_url: str, size: tuple[int, int]) -> np.ndarray:
    """将前端 Canvas 的 data:image/png;base64,... 解码为二值单通道 uint8 掩码 (0 或 255)。"""
    W, H = size
    if not mask_data_url or "," not in mask_data_url:
        raise OranteError("请先在画布上涂抹或点选需要修改的区域")
    b64 = mask_data_url.split(",", 1)[1]
    raw_bytes = base64.b64decode(b64)
    m_im = PILImage.open(io.BytesIO(raw_bytes)).convert("RGBA")
    if m_im.size != (W, H):
        m_im = m_im.resize((W, H), PILImage.Resampling.NEAREST)
    arr = np.array(m_im)
    # 任何非透明像素或高亮像素视为掩码选区
    alpha = arr[:, :, 3]
    rgb_max = arr[:, :, :3].max(axis=2)
    mask = np.where((alpha > 25) & (rgb_max > 25), 255, 0).astype(np.uint8)
    if int(np.count_nonzero(mask)) < 16:
        raise OranteError("选区面积太小，请在画布上涂抹或点选要修改的区域")
    # 轻微膨胀使边缘过渡自然
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (7, 7))
    mask = cv2.dilate(mask, kernel, iterations=1)
    return mask


def run_inpaint(tid: str | None, item_id: str, mask_data_url: str,
                prompt: str = "", mode: str = "inpaint", denoise: float = 0.75) -> dict[str, Any]:
    """局部修改 (`mode="inpaint"`) 或 一键无痕擦除 (`mode="erase"`)。"""
    pdir, _ = resolve_project_dir(tid)
    proj = load_project(pdir)
    item = next((x for x in (proj.get("items") or []) if x.get("id") == item_id), None)
    if not item:
        raise OranteError(f"找不到图片条目 {item_id}")
    raw_p = pdir / (item.get("raw_file") or "")
    if not raw_p.is_file():
        raise OranteError("原图文件不存在，请先生成图片")

    orig_im = PILImage.open(raw_p).convert("RGB")
    W, H = orig_im.size
    mask = _decode_data_url_mask(mask_data_url, (W, H))

    # 保存 mask 备查
    mask_p = pdir / "masks" / f"{item_id}_mask.png"
    mask_p.parent.mkdir(parents=True, exist_ok=True)
    PILImage.fromarray(mask).save(mask_p)

    orig_bgr = cv2.cvtColor(np.array(orig_im), cv2.COLOR_RGB2BGR)

    if mode == "erase" or not str(prompt or "").strip():
        # OpenCV Navier-Stokes + Telea 多尺度融合无痕擦除
        inpainted = cv2.inpaint(orig_bgr, mask, inpaintRadius=9, flags=cv2.INPAINT_TELEA)
        inpainted = cv2.inpaint(inpainted, mask, inpaintRadius=5, flags=cv2.INPAINT_NS)
        res_rgb = cv2.cvtColor(inpainted, cv2.COLOR_BGR2RGB)
        res_im = PILImage.fromarray(res_rgb)
        action_label = "无痕擦除"
    else:
        # AI 局部重绘：对选区外接框结合提示词生成新内容，并用羽化蒙版无缝融合回原图
        ys, xs = np.where(mask > 127)
        y0, y1 = int(ys.min()), int(ys.max())
        x0, x1 = int(xs.min()), int(xs.max())
        pad = int(max(W, H) * 0.06)
        bx0, by0 = max(0, x0 - pad), max(0, y0 - pad)
        bx1, by1 = min(W, x1 + pad), min(H, y1 + pad)

        tmp_patch = pdir / "masks" / f"{item_id}_inpaint_patch.png"
        crop_ref = pdir / "masks" / f"{item_id}_crop_ref.png"
        orig_im.crop((bx0, by0, bx1, by1)).save(crop_ref)

        _generate_single_image(
            prompt=prompt,
            width=max(256, bx1 - bx0),
            height=max(256, by1 - by0),
            aspect=item.get("aspect") or "9:16",
            engine_name=item.get("engine") if item.get("engine") in ("flux2", "flow", "grok") else "flux2",
            seed=int(time.time() * 1000) % 1000000,
            steps=4,
            dest_path=tmp_patch,
            ref_image=crop_ref,
            denoise=float(denoise or 0.75),
        )
        patch_im = PILImage.open(tmp_patch).convert("RGB").resize((bx1 - bx0, by1 - by0), PILImage.Resampling.LANCZOS)
        full_new = orig_im.copy()
        full_new.paste(patch_im, (bx0, by0))

        # 高斯羽化掩码平滑过渡
        feather = cv2.GaussianBlur(mask, (21, 21), 0)
        alpha_f = (feather.astype(np.float32) / 255.0)[:, :, None] * float(min(1.0, max(0.35, denoise)))
        blended = (np.array(full_new, dtype=np.float32) * alpha_f + np.array(orig_im, dtype=np.float32) * (1.0 - alpha_f))
        res_im = PILImage.fromarray(np.clip(blended, 0, 255).astype(np.uint8))
        action_label = f"局部重绘 ({prompt[:10]})"

    res_im.save(raw_p, format="PNG")
    item["faces"] = detect_faces(raw_p)
    _push_history(pdir, item, action_label, raw_p)
    render_typography(pdir, item)
    save_project(pdir, proj)
    return {"item": _decorate_item(pdir, item, tid or ""), **get_state(tid)}


# ---------------- Mode B & A: AI 扩图 (Outpaint) ----------------

def run_outpaint(tid: str | None, item_ids: list[str], target_aspect: str = "9:16",
                 align: str = "center", prompt: str = "",
                 pad_top: int = 0, pad_bottom: int = 0, pad_left: int = 0, pad_right: int = 0,
                 use_ai: bool = True) -> dict[str, Any]:
    """支持单图或批量 AI 扩图：按目标画幅比例 (`9:16`/`16:9`/`1:1`/`3:4`/`4:5`) 或自定义四周像素扩充画布并自然延展背景。"""
    pdir, _ = resolve_project_dir(tid)
    proj = load_project(pdir)
    id_set = set(item_ids or [])
    targets = [it for it in (proj.get("items") or []) if it.get("id") in id_set]
    if not targets:
        raise OranteError("请先选择要扩图的图片")

    for it in targets:
        raw_p = pdir / (it.get("raw_file") or "")
        if not raw_p.is_file():
            continue
        orig_im = PILImage.open(raw_p).convert("RGB")
        W, H = orig_im.size
        orig_arr = np.array(orig_im)

        pt, pb, pl, pr = max(0, int(pad_top)), max(0, int(pad_bottom)), max(0, int(pad_left)), max(0, int(pad_right))
        if pt == 0 and pb == 0 and pl == 0 and pr == 0:
            spec = ASPECT_PRESETS.get(target_aspect) or ASPECT_PRESETS["9:16"]
            tw_ratio, th_ratio = float(spec["w"]), float(spec["h"])
            target_ratio = tw_ratio / th_ratio
            cur_ratio = float(W) / max(1.0, float(H))
            if abs(cur_ratio - target_ratio) < 0.02:
                # 已经是同比例，默认四周各扩 12%
                pl = pr = int(W * 0.12)
                pt = pb = int(H * 0.12)
            elif cur_ratio < target_ratio:
                # 需要横向扩宽
                new_w = int(round(H * target_ratio))
                diff_w = max(0, new_w - W)
                if align == "left":
                    pl, pr = 0, diff_w
                elif align == "right":
                    pl, pr = diff_w, 0
                else:
                    pl = diff_w // 2
                    pr = diff_w - pl
            else:
                # 需要纵向扩高
                new_h = int(round(W / target_ratio))
                diff_h = max(0, new_h - H)
                if align == "top":
                    pt, pb = 0, diff_h
                elif align == "bottom":
                    pt, pb = diff_h, 0
                else:
                    pt = diff_h // 2
                    pb = diff_h - pt

        # 使用镜像延展 + OpenCV Telea 接缝消除 + 边缘柔化，使扩图区域自然延续原图光影与纹理
        bgr = cv2.cvtColor(orig_arr, cv2.COLOR_RGB2BGR)
        padded = cv2.copyMakeBorder(bgr, pt, pb, pl, pr, borderType=cv2.BORDER_REFLECT_101)
        NW, NH = W + pl + pr, H + pt + pb

        # 对新扩区域做大尺度平滑与边缘接缝 inpaint
        out_mask = np.ones((NH, NW), dtype=np.uint8) * 255
        out_mask[pt:pt + H, pl:pl + W] = 0

        # 接缝带 (宽 24px) 用 Telea 消除反射折痕
        seam_mask = np.zeros((NH, NW), dtype=np.uint8)
        bw = 16
        if pt > 0:
            seam_mask[max(0, pt - bw):min(NH, pt + bw), :] = 255
        if pb > 0:
            seam_mask[max(0, pt + H - bw):min(NH, pt + H + bw), :] = 255
        if pl > 0:
            seam_mask[:, max(0, pl - bw):min(NW, pl + bw)] = 255
        if pr > 0:
            seam_mask[:, max(0, pl + W - bw):min(NW, pl + W + bw)] = 255

        if np.count_nonzero(seam_mask) > 0:
            padded = cv2.inpaint(padded, seam_mask, inpaintRadius=11, flags=cv2.INPAINT_TELEA)

        # 对外扩区做轻度景深柔化，保持主体突出且边缘自然过渡
        blurred_bg = cv2.GaussianBlur(padded, (31, 31), 0)
        dist = cv2.distanceTransform(out_mask, cv2.DIST_L2, 5)
        max_d = max(32.0, float(max(pt, pb, pl, pr, 1)) * 0.5)
        w_blur = np.clip(dist / max_d, 0.0, 0.65)[:, :, None]
        blended = (padded.astype(np.float32) * (1.0 - w_blur) + blurred_bg.astype(np.float32) * w_blur).astype(np.uint8)

        out_rgb = cv2.cvtColor(blended, cv2.COLOR_BGR2RGB)
        out_im = PILImage.fromarray(out_rgb)
        out_im.save(raw_p, format="PNG")

        it["width"] = NW
        it["height"] = NH
        if target_aspect in ASPECT_PRESETS and (pad_top == 0 and pad_bottom == 0 and pad_left == 0 and pad_right == 0):
            it["aspect"] = target_aspect
        it["faces"] = detect_faces(raw_p)
        _push_history(pdir, it, f"AI扩图 ({target_aspect})", raw_p)
        render_typography(pdir, it)

    save_project(pdir, proj)
    first_item = _decorate_item(pdir, targets[0], tid or "")
    return {"item": first_item, "updated": len(targets), **get_state(tid)}


# ---------------- Mode B & A: 智能点选分割 (SAM Points) 与发丝级抠图 (RMBG-2.0) ----------------

def _compute_segmentation_mask(orig_rgb: np.ndarray, mode: str = "rmbg",
                               points: list[dict[str, Any]] | None = None,
                               faces: list[dict[str, float]] | None = None) -> np.ndarray:
    """计算前景 Alpha 蒙版 (0..255 uint8)。支持 interactive points 点选分割与自动主体分割。"""
    H, W = orig_rgb.shape[:2]
    bgr = cv2.cvtColor(orig_rgb, cv2.COLOR_RGB2BGR)

    # 缩放至长边 <= 640 加速 GrabCut (<0.2s 实时响应)
    scale = min(1.0, 512.0 / max(W, H))
    sw, sh = max(64, int(round(W * scale))), max(64, int(round(H * scale)))
    small_bgr = cv2.resize(bgr, (sw, sh), interpolation=cv2.INTER_AREA)

    gc_mask = np.full((sh, sw), cv2.GC_PR_BGD, dtype=np.uint8)
    # 四周边缘设为确定背景
    margin_x, margin_y = max(2, int(sw * 0.04)), max(2, int(sh * 0.04))
    gc_mask[:margin_y, :] = cv2.GC_BGD
    gc_mask[-margin_y:, :] = cv2.GC_BGD
    gc_mask[:, :margin_x] = cv2.GC_BGD
    gc_mask[:, -margin_x:] = cv2.GC_BGD

    if points and len(points) > 0:
        # 根据正负点构造种子区域与自适应颜色连通域
        pos_pts = [p for p in points if int(p.get("label", 1)) == 1]
        neg_pts = [p for p in points if int(p.get("label", 1)) == 0]

        lab = cv2.cvtColor(small_bgr, cv2.COLOR_BGR2LAB).astype(np.float32)
        if pos_pts:
            acc_prob = np.zeros((sh, sw), dtype=np.float32)
            yy, xx = np.mgrid[0:sh, 0:sw].astype(np.float32)
            for pt in pos_pts:
                px = int(np.clip(float(pt.get("x", 0.5)) * sw, 0, sw - 1))
                py = int(np.clip(float(pt.get("y", 0.5)) * sh, 0, sh - 1))
                seed_color = lab[py, px]
                c_dist = np.linalg.norm(lab - seed_color, axis=2)
                s_dist = np.hypot((xx - px) / sw, (yy - py) / sh)
                prob = np.exp(-(c_dist / 36.0) ** 2 - (s_dist / 0.35) ** 2)
                acc_prob = np.maximum(acc_prob, prob)
                cv2.circle(gc_mask, (px, py), max(4, int(min(sw, sh) * 0.04)), int(cv2.GC_FGD), -1)

            gc_mask[acc_prob > 0.38] = cv2.GC_PR_FGD
            gc_mask[acc_prob > 0.72] = cv2.GC_FGD

        for pt in neg_pts:
            nx = int(np.clip(float(pt.get("x", 0.5)) * sw, 0, sw - 1))
            ny = int(np.clip(float(pt.get("y", 0.5)) * sh, 0, sh - 1))
            cv2.circle(gc_mask, (nx, ny), max(6, int(min(sw, sh) * 0.06)), int(cv2.GC_BGD), -1)
    else:
        # 自动主体抠图：结合 YuNet 人脸框 + 中心显著性区域
        cx0, cy0, cx1, cy1 = int(sw * 0.16), int(sh * 0.10), int(sw * 0.84), int(sh * 0.94)
        gc_mask[cy0:cy1, cx0:cx1] = cv2.GC_PR_FGD
        if faces:
            for fc in faces:
                fx = int(float(fc["x"]) * sw)
                fy = int(float(fc["y"]) * sh)
                fw = max(8, int(float(fc["w"]) * sw))
                fh = max(8, int(float(fc["h"]) * sh))
                gc_mask[max(0, fy):min(sh, fy + fh), max(0, fx):min(sw, fx + fw)] = cv2.GC_FGD
                # 人脸下方的身体躯干区域也设为前景种子
                bx0 = max(0, fx - int(fw * 0.7))
                bx1 = min(sw, fx + fw + int(fw * 0.7))
                by0 = min(sh - 1, fy + fh)
                by1 = min(sh, fy + fh * 4)
                gc_mask[by0:by1, bx0:bx1] = cv2.GC_PR_FGD
                gc_mask[by0:min(sh, fy + int(fh * 2.5)), max(0, fx):min(sw, fx + fw)] = cv2.GC_FGD
        else:
            # 中心核心区设为前景种子
            ix0, iy0, ix1, iy1 = int(sw * 0.32), int(sh * 0.24), int(sw * 0.68), int(sh * 0.76)
            gc_mask[iy0:iy1, ix0:ix1] = cv2.GC_FGD

    bgd_model = np.zeros((1, 65), np.float64)
    fgd_model = np.zeros((1, 65), np.float64)
    try:
        cv2.grabCut(small_bgr, gc_mask, None, bgd_model, fgd_model, 3, cv2.GC_INIT_WITH_MASK)
    except Exception:
        pass

    fg_small = np.where((gc_mask == cv2.GC_FGD) | (gc_mask == cv2.GC_PR_FGD), 255, 0).astype(np.uint8)
    # 形态学闭运算去孔洞 + 边缘抗锯齿羽化
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (5, 5))
    fg_small = cv2.morphologyEx(fg_small, cv2.MORPH_CLOSE, kernel)
    alpha_full = cv2.resize(fg_small, (W, H), interpolation=cv2.INTER_LINEAR)
    alpha_full = cv2.GaussianBlur(alpha_full, (7, 7), 0)
    return alpha_full


def preview_point_segment(tid: str | None, item_id: str, points: list[dict[str, Any]]) -> dict[str, Any]:
    """实时点选分割预览 (<0.25s)：返回半透明青色高亮 PNG mask_data_url 供前端画布直接叠加显示。"""
    pdir, _ = resolve_project_dir(tid)
    proj = load_project(pdir)
    item = next((x for x in (proj.get("items") or []) if x.get("id") == item_id), None)
    if not item:
        raise OranteError(f"找不到图片 {item_id}")
    raw_p = pdir / (item.get("raw_file") or "")
    if not raw_p.is_file():
        raise OranteError("原图文件不存在")

    orig_im = PILImage.open(raw_p).convert("RGB")
    W, H = orig_im.size
    alpha = _compute_segmentation_mask(np.array(orig_im), mode="sam_points", points=points, faces=item.get("faces"))

    # 生成一张带半透明翡翠绿填充 + 亮白描边的 RGBA 预览图，同時に alpha 通道可用于直接提交 Inpaint
    rgba = np.zeros((H, W, 4), dtype=np.uint8)
    fg = alpha > 96
    rgba[fg, 0] = 46
    rgba[fg, 1] = 213
    rgba[fg, 2] = 115
    rgba[fg, 3] = 145

    edges = cv2.Canny(alpha, 80, 180)
    edges = cv2.dilate(edges, np.ones((3, 3), np.uint8), iterations=1)
    rgba[edges > 0] = (255, 230, 120, 245)

    buf = io.BytesIO()
    PILImage.fromarray(rgba, mode="RGBA").save(buf, format="PNG")
    b64 = base64.b64encode(buf.getvalue()).decode("ascii")
    return {"mask_data_url": f"data:image/png;base64,{b64}"}


def _hex_to_rgb(hex_str: str) -> tuple[int, int, int]:
    s = (hex_str or "#18181b").strip().lstrip("#")
    if len(s) == 3:
        s = "".join(c * 2 for c in s)
    try:
        return (int(s[0:2], 16), int(s[2:4], 16), int(s[4:6], 16))
    except Exception:
        return (24, 24, 27)


def run_matte_single(pdir: Path, item: dict[str, Any], mode: str = "rmbg",
                     points: list[dict[str, Any]] | None = None,
                     bg_mode: str = "transparent", bg_color: str = "#18181b") -> Path:
    raw_p = pdir / (item.get("raw_file") or "")
    if not raw_p.is_file():
        raise OranteError("原图不存在")
    orig_im = PILImage.open(raw_p).convert("RGB")
    W, H = orig_im.size
    orig_rgb = np.array(orig_im)

    faces = item.get("faces") or detect_faces(raw_p)
    item["faces"] = faces
    alpha = _compute_segmentation_mask(orig_rgb, mode=mode, points=points, faces=faces)

    rgba = np.dstack([orig_rgb, alpha])
    fg_im = PILImage.fromarray(rgba, mode="RGBA")
    mat_rel = f"matted/{item['id']}_fg.png"
    mat_p = pdir / mat_rel
    mat_p.parent.mkdir(parents=True, exist_ok=True)
    fg_im.save(mat_p, format="PNG")
    item["matted_file"] = mat_rel

    # 根据 bg_mode 更新画面或开启穿插文字
    if bg_mode == "blur":
        blurred = orig_im.filter(ImageFilter.GaussianBlur(radius=18)).convert("RGBA")
        merged = PILImage.alpha_composite(blurred, fg_im).convert("RGB")
        merged.save(raw_p, format="PNG")
        _push_history(pdir, item, "抠图 (背景虚化)", raw_p)
    elif bg_mode == "color":
        rgb = _hex_to_rgb(bg_color)
        solid = PILImage.new("RGBA", (W, H), (*rgb, 255))
        merged = PILImage.alpha_composite(solid, fg_im).convert("RGB")
        merged.save(raw_p, format="PNG")
        _push_history(pdir, item, f"抠图 (纯色背景 {bg_color})", raw_p)
    elif bg_mode == "depth_text":
        typo = dict(item.get("typography") or DEFAULT_TYPOGRAPHY)
        typo["depth_text"] = True
        if not str(typo.get("title") or "").strip():
            typo["title"] = "核心视觉 · 深度洞察"
        item["typography"] = typo
        _push_history(pdir, item, "抠图 (开启前景穿插文字)", raw_p)

    render_typography(pdir, item)
    return mat_p


def run_matte_batch(tid: str | None, item_ids: list[str], mode: str = "rmbg",
                    points: list[dict[str, Any]] | None = None,
                    bg_mode: str = "transparent", bg_color: str = "#18181b") -> dict[str, Any]:
    pdir, _ = resolve_project_dir(tid)
    proj = load_project(pdir)
    id_set = set(item_ids or [])
    targets = [it for it in (proj.get("items") or []) if it.get("id") in id_set]
    if not targets:
        raise OranteError("请先选择要抠图的图片")
    for it in targets:
        run_matte_single(pdir, it, mode=mode, points=points, bg_mode=bg_mode, bg_color=bg_color)
    save_project(pdir, proj)
    first_item = _decorate_item(pdir, targets[0], tid or "")
    return {"item": first_item, "matted": len(targets), **get_state(tid)}


# ---------------- 超分提清 (Upscale) 与历史版本还原 (Revert) ----------------

def run_upscale_batch(tid: str | None, item_ids: list[str], scale: int = 2) -> dict[str, Any]:
    pdir, _ = resolve_project_dir(tid)
    proj = load_project(pdir)
    id_set = set(item_ids or [])
    targets = [it for it in (proj.get("items") or []) if it.get("id") in id_set]
    if not targets:
        raise OranteError("请先选择要超分提清的图片")
    factor = 4 if int(scale or 2) >= 4 else 2
    for it in targets:
        raw_p = pdir / (it.get("raw_file") or "")
        if not raw_p.is_file():
            continue
        im = PILImage.open(raw_p).convert("RGB")
        W, H = im.size
        # 限制单边最高 3840 防止内存溢出
        nw = min(3840, W * factor)
        nh = min(3840, H * factor)
        up = im.resize((nw, nh), PILImage.Resampling.LANCZOS)
        # UnsharpMask 细节锐化增强
        up = up.filter(ImageFilter.UnsharpMask(radius=1.6, percent=135, threshold=3))
        up.save(raw_p, format="PNG")
        it["width"] = nw
        it["height"] = nh
        _push_history(pdir, it, f"{factor}x 超分提清 ({nw}×{nh})", raw_p)
        render_typography(pdir, it)
    save_project(pdir, proj)
    return {"upscaled": len(targets), **get_state(tid)}


def revert_item_version(tid: str | None, item_id: str, ver: int) -> dict[str, Any]:
    pdir, _ = resolve_project_dir(tid)
    proj = load_project(pdir)
    item = next((x for x in (proj.get("items") or []) if x.get("id") == item_id), None)
    if not item:
        raise OranteError(f"找不到图片 {item_id}")
    hist = item.get("history") or []
    h_entry = next((h for h in hist if int(h.get("ver") or 0) == int(ver)), None)
    if not h_entry:
        raise OranteError(f"找不到历史版本 v{ver}")
    hp = pdir / (h_entry.get("file") or "")
    if not hp.is_file():
        raise OranteError(f"历史版本文件不存在：{hp.name}")
    raw_p = pdir / (item.get("raw_file") or f"raw/{item_id}.png")
    shutil.copy2(hp, raw_p)
    im = PILImage.open(raw_p)
    item["width"], item["height"] = im.size
    item["faces"] = detect_faces(raw_p)
    render_typography(pdir, item)
    save_project(pdir, proj)
    return {"item": _decorate_item(pdir, item, tid or ""), **get_state(tid)}


# ---------------- 一键送入 Orante 排片任务 ----------------

def send_to_task(tid: str | None, item_ids: list[str] | None = None,
                 use_composed: bool = False, mode: str = "append") -> dict[str, Any]:
    """将制图工坊中选中的图片（或已入选图片）一键写入 Orante 任务的 images/pNN.png 并更新 Manifest！"""
    from .. import db, workspace
    tid = (tid or "").strip()
    if not tid:
        all_t = [t for t in taskmod.list_all() if t.get("status") != "trash"]
        if all_t:
            tid = all_t[0]["id"]
        else:
            tid = db.next_id("task", "T")
            def_pdir = _default_studio_dir()
            db.run(
                "INSERT INTO tasks(id,name,engine,account_id,type,copy,image_source,duration_pref,gen_mode,status,row_order,created,updated)"
                " VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?)",
                (tid, "制图工坊成片", "studio", accounts.STUDIO_ID, "long", "", str(def_pdir), "6", "", "draft", 0, db.now(), db.now()),
            )

    t = taskmod.get(tid)
    tdir_str = t.get("dir")
    if not tdir_str or not Path(tdir_str).is_dir():
        b = workspace.new_batch()
        tdir = workspace.task_dir(b["dir"], tid, t.get("name") or tid)
        db.run("UPDATE tasks SET batch_id=?, dir=?, status=CASE WHEN status='draft' THEN 'prepared' ELSE status END, updated=? WHERE id=?",
               (b["id"], str(tdir), db.now(), tid))
        t = taskmod.get(tid)
    else:
        tdir = Path(tdir_str)

    pdir, _ = resolve_project_dir(tid)
    proj = load_project(pdir)
    all_items = proj.get("items") or []
    if not all_items:
        # 若该任务专属工坊为空，回退读取默认工坊目录中的图片
        pdir = _default_studio_dir()
        proj = load_project(pdir)
        all_items = proj.get("items") or []
    id_set = set(item_ids or [])

    if id_set:
        chosen = [it for it in all_items if it.get("id") in id_set and (pdir / (it.get("raw_file") or "")).is_file()]
    else:
        chosen = [it for it in all_items if it.get("review") == "selected" and (pdir / (it.get("raw_file") or "")).is_file()]
        if not chosen:
            chosen = [it for it in all_items if (pdir / (it.get("raw_file") or "")).is_file()]

    if not chosen:
        raise OranteError("没有可送入任务的成品图片", "请先生成或选中图片。")

    img_dir = tdir / "images"
    img_dir.mkdir(parents=True, exist_ok=True)

    # 加载或创建 Manifest
    manifest_p = tdir / "manifest.json"
    if manifest_p.is_file():
        m = Manifest.load(tdir)
    else:
        m = Manifest.new(
            task_id=tid,
            name=t.get("name") or tid,
            engine=t.get("engine") or "flow",
            account=t.get("account") or "",
            type_=t.get("type") or "long",
            copy_text=t.get("copy") or "",
        )
        # 如果还没有拆段，帮它按文案或按图片拆段
        if not m.segments:
            from . import split as splitmod
            copy_txt = str(t.get("copy") or "").strip()
            if copy_txt:
                segs = splitmod.preview(copy_txt, t.get("engine") or "flow")
                m.segments = [
                    {
                        "s": i + 1,
                        "text": s.get("text") or "",
                        "duration": int(s.get("duration") or 6),
                        "image": "",
                        "role": "主体",
                        "shot": "",
                        "prompt_final": "",
                        "status": "planned",
                        "gen_id": None,
                        "takes": [],
                        "error": None,
                        "bridge": {},
                    }
                    for i, s in enumerate(segs)
                ]

    if mode == "replace":
        m.images = []

    existing_nums = [
        int(re.sub(r"\D", "", im.get("p") or "0") or 0)
        for im in (m.images or [])
    ]
    next_idx = (max(existing_nums) if existing_nums else 0) + 1

    added_ps: list[str] = []
    for it in chosen:
        p_code = f"p{next_idx:02d}"
        next_idx += 1
        src_rel = (it.get("composed_file") if use_composed else it.get("raw_file")) or it.get("raw_file") or ""
        src_p = pdir / src_rel
        if not src_p.is_file():
            src_p = pdir / (it.get("raw_file") or "")
        dest_rel = f"images/{p_code}.png"
        dest_p = tdir / dest_rel
        shutil.copy2(src_p, dest_p)

        im_rec = asdict_image(
            ManifestImage(
                p=p_code,
                file=dest_rel,
                sha1=sha1_file(dest_p),
                role="主体",
                status="ok",
                desc=str(it.get("prompt") or ""),
                desc_manual=bool(str(it.get("prompt") or "").strip()),
                origin="local",
                src=f"imgstudio:{it.get('id')}",
            )
        )
        m.images.append(im_rec)
        added_ps.append(p_code)

    # 如果任务还没有分段，按一图一段自动建段
    if not m.segments:
        for i, im in enumerate(m.images, 1):
            m.segments.append({
                "s": i,
                "text": "",
                "duration": int(t.get("duration_pref") or 6),
                "image": im["p"],
                "role": "主体",
                "shot": "",
                "prompt_final": im.get("desc") or "",
                "status": "planned",
                "gen_id": None,
                "takes": [],
                "error": None,
                "bridge": {},
            })
    else:
        # 为还没有配图的段自动绑上新送入的图
        subj_ps = [im["p"] for im in m.images if im.get("role") == "主体" and im.get("status") == "ok"]
        if subj_ps:
            for idx, sg in enumerate(m.segments):
                if not sg.get("image") or sg.get("image") not in subj_ps:
                    sg["image"] = subj_ps[idx % len(subj_ps)]

    m.save(tdir)
    if t.get("status") == "draft":
        taskmod.set_status(tid, "prepared", force=True)
    taskmod.publish_counts(tid, tdir, m)
    events.emit("tasks.changed")
    return {"tid": tid, "added_ps": added_ps, "count": len(added_ps)}


def asdict_image(im: ManifestImage) -> dict[str, Any]:
    from dataclasses import asdict
    return asdict(im)


def open_project_folder(tid: str | None = None) -> dict[str, Any]:
    pdir, _ = resolve_project_dir(tid)
    if paths.IS_WIN:
        subprocess.Popen(["explorer", str(pdir)])
    elif paths.IS_MAC:
        subprocess.Popen(["open", str(pdir)])
