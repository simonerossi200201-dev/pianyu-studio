    function onKeyDown(ev) {
      const el = ev.target;
      if (el && (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA' || el.tagName === 'SELECT' || el.isContentEditable)) {
        return;
      }
      if (ev.key === 'Tab') {
        ev.preventDefault();
        if (viewMode.value === 'grid') {
          if (activeItem.value) openInCanvas(activeItem.value);
        } else {
          viewMode.value = 'grid';
        }
        return;
      }
      if (ev.key === 'Escape' && viewMode.value === 'canvas') {
        viewMode.value = 'grid';
        return;
      }
      const list = filteredItems.value;
      if (!list.length) return;
      const curIdx = list.findIndex(x => x.id === activeItemId.value);
      if (ev.key === 'ArrowRight' || ev.key === 'ArrowDown') {
        ev.preventDefault();
        const next = list[Math.min(list.length - 1, curIdx + 1)] || list[0];
        if (next) {
          activeItemId.value = next.id;
          syncActiveItemToInspector(next);
          if (viewMode.value === 'canvas') nextTick(() => initMaskCanvas());
        }
      } else if (ev.key === 'ArrowLeft' || ev.key === 'ArrowUp') {
        ev.preventDefault();
        const prev = list[Math.max(0, curIdx - 1)] || list[0];
        if (prev) {
          activeItemId.value = prev.id;
          syncActiveItemToInspector(prev);
          if (viewMode.value === 'canvas') nextTick(() => initMaskCanvas());
        }
      } else if (ev.key === '1' || ev.key === 'Enter') {
        if (activeItem.value) setReview([activeItem.value.id], 'selected');
      } else if (ev.key === 'x' || ev.key === 'X') {
        if (activeItem.value) setReview([activeItem.value.id], 'rejected');
      } else if (ev.key === 'e' || ev.key === 'E') {
        if (activeItem.value) openInCanvas(activeItem.value);
      } else if (ev.key === 'r' || ev.key === 'R') {
        if (activeItem.value && !ev.ctrlKey && !ev.metaKey) generateBatch(false, [activeItem.value.id]);
      }
    }

