"""Q150 · 自动保存不许把上一次会话没保存的改动盖掉（2026-09-29 事故复现）。

Luca 15:49 手动存盘，16:41–17:04 加标题（只在自动保存里），软件没了；重开工程后
第一次自动保存把那份快照覆盖 → 标题全丢。现在：别的会话留下的快照在第一次被覆盖
前先复制进备份；打开工程时发现「比工程新、内容不一样」的快照就问要不要恢复。"""
from __future__ import annotations

import json
import os
import time


def _fresh(monkeypatch, tmp_path):
    monkeypatch.setenv("CUTORA_USER_DATA", str(tmp_path / "ud"))
    import cutora.core.autosave as A
    A.reset_throttle_for_tests()
    assert A.backup_dir().startswith(str(tmp_path))   # 不会写到真用户目录
    return A


def _write_project(path, titles):
    data = {"version": 1, "tasks": [{"video": "v07.mp4", "text_overlays": [
        {"content": t} for t in titles]}]}
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(data, fh, ensure_ascii=False)
    return data


def test_previous_session_snapshot_survives_reopen(tmp_path, monkeypatch):
    A = _fresh(monkeypatch, tmp_path)
    proj = str(tmp_path / "2026-09-28.cutora")
    saved = _write_project(proj, ["Generated by AI"])
    # 上一个会话：加了标题，只进了自动保存
    side = A.sidecar_path(proj)
    lost = {"version": 1, "tasks": [{"video": "v07.mp4", "text_overlays": [
        {"content": "Generated by AI"}, {"content": "BEFORE JESUS RETURNS"}]}],
            "_autosave": {"at": "x", "project": proj, "session": "old-session"}}
    with open(side, "w", encoding="utf-8") as fh:
        json.dump(lost, fh)
    later = time.time() + 5
    os.utime(side, (later, later))
    assert A.unsaved_leftover(proj) == side
    # 这次会话：重新打开工程后第一次自动保存（内容是工程文件里那份）
    A.write_snapshot(proj, saved)
    backups = A.list_backups(proj)
    assert len(backups) == 1
    with open(backups[0], encoding="utf-8") as fh:
        kept = json.load(fh)
    titles = [o["content"] for o in kept["tasks"][0]["text_overlays"]]
    assert "BEFORE JESUS RETURNS" in titles
    # 自己这次写的快照再写不会再备份
    A.write_snapshot(proj, saved)
    assert len(A.list_backups(proj)) == 1
    with open(side, encoding="utf-8") as fh:
        assert json.load(fh)["_autosave"]["session"] == A.SESSION_ID
    assert A.unsaved_leftover(proj) is None      # 自己的快照不算「上次没保存」


def test_no_prompt_when_snapshot_equals_project(tmp_path, monkeypatch):
    A = _fresh(monkeypatch, tmp_path)
    proj = str(tmp_path / "p.cutora")
    data = _write_project(proj, ["a"])
    side = A.sidecar_path(proj)
    with open(side, "w", encoding="utf-8") as fh:
        json.dump(dict(data, _autosave={"session": "old"}), fh)
    later = time.time() + 5
    os.utime(side, (later, later))
    assert A.unsaved_leftover(proj) is None


def test_clean_save_does_not_delete_foreign_snapshot_without_backup(tmp_path, monkeypatch):
    A = _fresh(monkeypatch, tmp_path)
    proj = str(tmp_path / "q.cutora")
    _write_project(proj, ["a"])
    side = A.sidecar_path(proj)
    with open(side, "w", encoding="utf-8") as fh:
        json.dump({"tasks": [], "_autosave": {"session": "old"}}, fh)
    A.clear_snapshot(proj)
    assert not os.path.exists(side)
    assert len(A.list_backups(proj)) == 1


def test_backups_are_capped(tmp_path, monkeypatch):
    A = _fresh(monkeypatch, tmp_path)
    proj = str(tmp_path / "r.cutora")
    _write_project(proj, ["a"])
    side = A.sidecar_path(proj)
    for i in range(A.BACKUP_KEEP + 3):
        with open(side, "w", encoding="utf-8") as fh:
            json.dump({"tasks": [i], "_autosave": {"session": "s%d" % i}}, fh)
        t = time.time() - 1000 + i * 10
        os.utime(side, (t, t))
        A._checked_dest.clear()
        assert A.preserve_foreign_snapshot(side)
    assert len(A.list_backups(proj)) == A.BACKUP_KEEP
