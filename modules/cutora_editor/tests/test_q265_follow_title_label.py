"""Q265：「图片接在标题后面，直到这条视频结束」不被整条视频的角标带偏。

Luca 2026-10-12：Text 1 是从 0 秒挂到结尾的「Generated by AI #xy」，Text 2 是标题。
两条都从 0 秒开始，角标排前面被当成标题 → 结尾放不下图 → 回退成手填时间。
"""
from __future__ import annotations

import pytest

from cutora.batch.text_batch import follow_title_span


def test_full_length_label_is_not_the_title():
    dur = 42.0
    task = {"text_overlays": [
        {"start": 0.0, "end": dur, "content": "Generated by AI #xy"},
        {"start": 0.0, "end": 5.3, "content": "IF YOU GO TO"},
    ]}
    got = follow_title_span(task, [], "", dur)
    assert got is not None, "full-length label hid the title"
    assert got[0] == pytest.approx(5.3)
    assert got[1] == pytest.approx(dur)
    assert got[2] == "overlay"


def test_label_order_does_not_matter():
    dur = 30.0
    task = {"text_overlays": [
        {"start": 0.0, "end": 4.0, "content": "title"},
        {"start": 0.0, "end": 29.98, "content": "watermark"},
    ]}
    got = follow_title_span(task, [], "", dur)
    assert got[0] == pytest.approx(4.0)


def test_only_a_label_means_no_follow():
    dur = 20.0
    task = {"text_overlays": [{"start": 0.0, "end": dur}]}
    assert follow_title_span(task, [], "", dur) is None


def test_same_start_prefers_the_longer_title():
    dur = 60.0
    task = {"text_overlays": [
        {"start": 0.0, "end": 1.5},
        {"start": 0.0, "end": 6.0},
    ]}
    assert follow_title_span(task, [], "", dur)[0] == pytest.approx(6.0)
