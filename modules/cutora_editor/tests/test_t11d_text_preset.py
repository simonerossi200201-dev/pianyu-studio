def test_cli_add_text_overlay_uses_new_store(preset_paths, tmp_path):
    from cutora.batch.cli import op_add_text_overlay

    proj = tmp_path / "p.asproj.json"
    proj.write_text(json.dumps({"tasks": [_task()]}, ensure_ascii=False), encoding="utf-8")
    out = op_add_text_overlay({"project": str(proj), "replace": True}, cmd={})
    assert out["ok"] is True
    assert out["preset"] == "credit.default"
    data = json.loads(proj.read_text(encoding="utf-8"))
    ovs = data["tasks"][0]["text_overlays"]
    assert len(ovs) == 1
    assert ovs[0]["source_preset_id"] == "credit.default"
    assert ovs[0]["content"] == "Generated with AI"

    out2 = op_add_text_overlay(
        {"project": str(proj), "preset": "credit.default", "replace": True}, cmd={})
    assert out2["preset"] == "credit.default"
    data2 = json.loads(proj.read_text(encoding="utf-8"))
    ovs2 = data2["tasks"][0]["text_overlays"]
    credits = [ov for ov in ovs2 if ov.get("source_preset_id") == "credit.default"]
    assert len(credits) == 1


