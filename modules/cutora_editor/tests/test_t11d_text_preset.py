@pytest.fixture
def preset_paths(tmp_path, monkeypatch):
    user = tmp_path / "text_presets.json"
    legacy = tmp_path / "text_style_presets.json"
    monkeypatch.setattr(TP, "_user_path", lambda: str(user))
    monkeypatch.setattr(TP, "_legacy_path", lambda: str(legacy))
    monkeypatch.setattr(PM, "TEXT_STYLE_PRESETS_PATH", str(legacy))
    TP.reset_runtime_state_for_tests()
    return user, legacy


def _task(w=1080, h=1920, duration=8.0):
    return {
        "dims": [w, h],
        "duration": duration,
        "text_overlays": [],
        "segments": [{"start": 0, "end": duration, "text": "hi"}],
    }


def test_create_user_preset_survives_restart(preset_paths):
    user, _legacy = preset_paths
    saved = TP.save_preset({
        "id": "p_persist",
        "name": "自定义署名",
        "text": "hello persist",
        "style": {"color": "#EEEEEE", "font_family": "Arimo"},
        "layout": {"anchor": "top_left", "margin_x": 0.1, "margin_y": 0.2, "size_pct": 0.04},
        "created_at": "2026-09-15T00:00:00Z",
        "updated_at": "2026-09-15T00:00:00Z",
    })
    assert saved["id"] == "p_persist"
    assert user.is_file()
    TP.reset_runtime_state_for_tests()
    loaded = TP.get_preset("p_persist")
    assert loaded is not None
    assert loaded["text"] == "hello persist"
    assert loaded["name"] == "自定义署名"
    assert loaded["layout"]["anchor"] == "top_left"
    names = {p["name"] for p in TP.list_presets()}
    assert "自定义署名" in names
    assert "署名" in names


def test_edit_user_preset_survives_restart(preset_paths):
    TP.save_preset({
        "id": "p_edit",
        "name": "可改",
        "text": "before",
        "style": {"color": "#ABCDEF"},
        "created_at": "2026-09-15T00:00:00Z",
        "updated_at": "2026-09-15T00:00:00Z",
    })
    TP.reset_runtime_state_for_tests()
    row = TP.get_preset("p_edit")
    assert row["text"] == "before"
    row["text"] = "after-edit"
    row["style"]["color"] = "#123456"
    TP.save_preset(row)
    TP.reset_runtime_state_for_tests()
    again = TP.get_preset("p_edit")
    assert again["text"] == "after-edit"
    assert again["style"]["color"] == "#123456"


