def test_product_code_has_no_hardcoded_legacy_preset_names():
    import pathlib
    root = pathlib.Path(__file__).resolve().parents[1] / "cutora"
    hits = []
    for path in root.rglob("*.py"):
        text = path.read_text(encoding="utf-8")
        for needle in ("Mio 署名", "AI 署名"):
            if needle in text:
                hits.append("%s: %s" % (path.relative_to(root.parent).as_posix(), needle))
    assert hits == [], hits


