def test_text_preset_has_no_silent_50_cap(preset_paths):
    """Subtitle named presets cap at 50; text presets must not silently no-op."""
    assert not hasattr(TP, "MAX_PRESETS")
    for i in range(51):
        TP.save_preset({
            "id": "p_cap_%02d" % i,
            "name": "cap-%02d" % i,
            "text": "t%d" % i,
            "created_at": "2026-09-15T00:00:00Z",
            "updated_at": "2026-09-15T00:00:00Z",
        })
    users = TP.load_user()
    assert len(users) == 51
    assert TP.get_preset("p_cap_50")["text"] == "t50"


def test_migrate_old_json_once_never_writes_it(preset_paths):
    user, legacy = preset_paths
    payload = {
        "default": {"content": "Generated by AI #xy "},
        "presets": {
            "AI 署名": {"content": "Generated by AI #xy ", "color": "#EEEEEE"},
            "片尾": {"content": "END", "color": "#FEFEFE", "font_family": "Arimo"},
        },
        "default_preset_name": "片尾",
    }
    legacy.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    before = legacy.read_bytes()
    mtime = legacy.stat().st_mtime

    TP.ensure_legacy_migrated()
    assert user.is_file()
    assert legacy.read_bytes() == before
    assert legacy.stat().st_mtime == mtime

    names = {p["name"]: p for p in TP.list_presets()}
    assert "署名" in names
    assert "AI 署名" in names
    assert "片尾" in names
    assert names["片尾"]["text"] == "END"
    assert names["片尾"]["id"].startswith("legacy.")
    assert TP.get_default_preset_id() == names["片尾"]["id"]

    TP.save_preset({
        "id": "p_after",
        "name": "迁移后新建",
        "text": "new",
        "created_at": "2026-09-15T00:00:00Z",
        "updated_at": "2026-09-15T00:00:00Z",
    })
    assert legacy.read_bytes() == before
    PM.save_named_text_preset("adapter", {"content": "via adapter", "color": "#CCCCCC"})
    assert legacy.read_bytes() == before
    assert not PM._save_text_preset_file({"presets": {}})


