"""Four-state QSS contract for interactive controls.

Do not hand-write a single :hover / :pressed / :focus / :disabled rule.
``four_states()`` refuses a missing state. ``render_states()`` is appended
to the generated QSS so every interactive class has a complete set.
"""
from __future__ import annotations

DISABLED_OPACITY = 0.35

# Widget classes that take pointer or keyboard input. The QSS scanner in
# tests walks the *rendered* stylesheet, not a file list.
INTERACTIVE_CLASSES = (
    "QPushButton",
    "QToolButton",
    "QSlider",
    "QCheckBox",
    "QRadioButton",
    "QLineEdit",
    "QSpinBox",
    "QDoubleSpinBox",
    "QComboBox",
    "QTextEdit",
    "QPlainTextEdit",
)

# Keyboard walkthrough: these seven must show a focus ring.
FOCUS_RING_SELECTORS = (
    "QPushButton",
    "QToolButton",
    "QSlider",
    "QCheckBox",
    "QToolButton#inspectorReset",
    "QWidget#swatchBtn",
    "QWidget#sectionToggle",
)

_STATES = ("hover", "pressed", "focus", "disabled")


def mix_disabled_rgb(rgb, bg_rgb, opacity: float = DISABLED_OPACITY):
    """Desaturate ``rgb`` to luma, then mix with ``bg_rgb`` at ``opacity``.

    35% of the grayed color over bg2 is what a closed inspector section
    should look like: no leftover accent gold, no full-sat swatch.
    """
    r, g, b = (int(rgb[0]), int(rgb[1]), int(rgb[2]))
    br, bg, bb = (int(bg_rgb[0]), int(bg_rgb[1]), int(bg_rgb[2]))
    luma = 0.2126 * r + 0.7152 * g + 0.0722 * b
    t = max(0.0, min(1.0, float(opacity)))
    return (
        int(round(luma * t + br * (1.0 - t))),
        int(round(luma * t + bg * (1.0 - t))),
        int(round(luma * t + bb * (1.0 - t))),
    )


def four_states(selector: str, *, hover: str, pressed: str, focus: str, disabled: str) -> str:
    """Emit hover/pressed/focus/disabled for ``selector``. All four required."""
    parts = {
        "hover": hover,
        "pressed": pressed,
        "focus": focus,
        "disabled": disabled,
    }
    missing = [name for name in _STATES if not str(parts[name]).strip()]
    if missing:
        raise ValueError(
            "four-state contract forbids missing %s on %s"
            % (", ".join(missing), selector)
        )
    blocks = []
    for name in _STATES:
        body = str(parts[name]).strip().rstrip(";")
        blocks.append("%s:%s { %s; }" % (selector, name, body))
    return "\n".join(blocks)


def render_states(ctx: dict) -> str:
    """Canonical four-state blocks. Appended after the Jinja QSS."""
    fg_muted = ctx.get("fg_muted") or ctx["fg2"]
    pressed_bg = ctx.get("pressed_bg") or ctx["bg1"]
    accent = ctx["accent"]
    line = ctx["line"]
    bg1 = ctx["bg1"]
    bg2 = ctx["bg2"]
    bg3 = ctx["bg3"]
    fg0 = ctx["fg0"]
    fg0_10 = ctx.get("fg0_10") or line

    hover_bg = "background-color: %s" % bg3
    pressed = "background-color: %s" % pressed_bg
    focus = "border-color: %s" % accent
    disabled = "color: %s; background-color: %s; border-color: %s" % (
        fg_muted, bg1, line)

    chunks = [
        "/* four-state contract — generated by cutora.ui.theme.states */",
        four_states(
            "QPushButton",
            hover="background-color: %s; border-color: %s" % (bg2, ctx["accent_dim"]),
            pressed=pressed,
            focus=focus,
            disabled=disabled,
        ),
        four_states(
            "QToolButton",
            hover=hover_bg,
            pressed=pressed,
            focus=focus,
            disabled=disabled,
        ),
        four_states(
            "QSlider",
            hover="border-color: %s" % accent,
            pressed=pressed,
            focus="border: 1px solid %s" % accent,
            disabled="border-color: %s" % line,
        ),
        four_states(
            "QCheckBox",
            hover="color: %s" % fg0,
            pressed=pressed,
            focus="border: 1px solid %s" % accent,
            disabled="color: %s" % fg_muted,
        ),
        four_states(
            "QRadioButton",
            hover="color: %s" % fg0,
            pressed=pressed,
            focus="border: 1px solid %s" % accent,
            disabled="color: %s" % fg_muted,
        ),
        four_states(
            "QLineEdit",
            hover="border-color: %s" % accent,
            pressed=pressed,
            focus="border: 1px solid %s" % accent,
            disabled="color: %s; background-color: %s; border-color: %s" % (
                fg_muted, bg1, line),
        ),
        four_states(
            "QSpinBox",
            hover="border-color: %s" % accent,
            pressed=pressed,
            focus="border: 1px solid %s" % accent,
            disabled="color: %s; background-color: %s; border-color: %s" % (
                fg_muted, bg1, line),
        ),
        four_states(
            "QDoubleSpinBox",
            hover="border-color: %s" % accent,
            pressed=pressed,
            focus="border: 1px solid %s" % accent,
            disabled="color: %s; background-color: %s; border-color: %s" % (
                fg_muted, bg1, line),
        ),
        four_states(
            "QComboBox",
            hover="border-color: %s" % accent,
            pressed=pressed,
            focus="border: 1px solid %s" % accent,
            disabled="color: %s; background-color: %s; border-color: %s" % (
                fg_muted, bg1, line),
        ),
        four_states(
            "QTextEdit",
            hover="border-color: %s" % accent,
            pressed=pressed,
            focus="border: 1px solid %s" % accent,
            disabled="color: %s; background-color: %s; border-color: %s" % (
                fg_muted, bg1, line),
        ),
        four_states(
            "QPlainTextEdit",
            hover="border-color: %s" % accent,
            pressed=pressed,
            focus="border: 1px solid %s" % accent,
            disabled="color: %s; background-color: %s; border-color: %s" % (
                fg_muted, bg1, line),
        ),
        four_states(
            "QToolButton#inspectorReset",
            hover="color: %s; background: %s" % (fg0, fg0_10),
            pressed=pressed,
            focus="border: 1px solid %s" % accent,
            disabled="color: %s; background: transparent; border: none" % fg_muted,
        ),
        four_states(
            "QWidget#swatchBtn",
            hover="border: 1px solid %s" % accent,
            pressed=pressed,
            focus="border: 1px solid %s" % accent,
            disabled="border-color: %s" % fg_muted,
        ),
        four_states(
            "QWidget#sectionToggle",
            hover="border: 1px solid %s" % accent,
            pressed=pressed,
            focus="border: 1px solid %s" % accent,
            disabled="border-color: %s" % fg_muted,
        ),
        # Labels are not interactive; disabled still has to mute explicit colors.
        "\n".join((
            "QLabel:disabled,",
            "QLabel#inspectorLabel:disabled,",
            "QLabel#inspectorHex:disabled,",
            "QWidget#dockSubContent QLabel:disabled {",
            "    color: %s;" % fg_muted,
            "}",
        )),
        "\n".join((
            "QSlider::groove:horizontal:disabled,",
            "QWidget#dockSubContent QSlider::groove:horizontal:disabled {",
            "    background: %s;" % line,
            "}",
            "QSlider::handle:horizontal:disabled,",
            "QWidget#dockSubContent QSlider::handle:horizontal:disabled {",
            "    background: %s;" % fg_muted,
            "}",
            "QSlider::sub-page:horizontal:disabled,",
            "QWidget#dockSubContent QSlider::sub-page:horizontal:disabled {",
            "    background: %s;" % line,
            "}",
        )),
        "QToolButton:disabled { color: %s; background-color: %s; border-color: %s; }" % (
            fg_muted, bg1, line),
    ]
    return "\n\n".join(chunks) + "\n"
