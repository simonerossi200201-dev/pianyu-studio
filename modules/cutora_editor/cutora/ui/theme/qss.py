"""In-memory QSS render. tools/build_qss.py writes the same string to disk."""
from __future__ import annotations

import os

from cutora.core.paths import RESOURCES
from cutora.ui.theme.tokens import qss_context

_TEMPLATE_DIR = os.path.dirname(os.path.abspath(__file__))
_TEMPLATE_NAME = "theme_dark.qss.j2"
LUCIDE_DIR = os.path.join(RESOURCES, "icons", "lucide")
QSS_ICONS = (
    ("check.svg", "qss_check.svg", "fg0"),
    ("check.svg", "qss_check_disabled.svg", "fg_muted"),
    ("chevron-up.svg", "qss_chevron_up.svg", "fg1"),
    ("chevron-down.svg", "qss_chevron_down.svg", "fg1"),
)


def write_qss_icons(ctx: dict | None = None, dest_dir: str | None = None) -> list[str]:
    """Tint Lucide stems into ``dest_dir`` using the current (or given) context."""
    colors = ctx if ctx is not None else qss_context()
    out_dir = dest_dir or os.path.join(RESOURCES, "theme")
    os.makedirs(out_dir, exist_ok=True)
    written: list[str] = []
    for src_name, dest_name, token in QSS_ICONS:
        src = os.path.join(LUCIDE_DIR, src_name)
        dest = os.path.join(out_dir, dest_name)
        with open(src, encoding="utf-8") as fh:
            svg = fh.read()
        svg = svg.replace("currentColor", colors[token])
        with open(dest, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(svg)
        written.append(dest)
    return written


def render(ctx: dict | None = None) -> str:
    """Render the dark theme QSS from the Jinja template + token context."""
    from jinja2 import Environment, FileSystemLoader, StrictUndefined

    data = dict(qss_context() if ctx is None else ctx)
    env = Environment(
        loader=FileSystemLoader(_TEMPLATE_DIR),
        undefined=StrictUndefined,
        keep_trailing_newline=True,
        autoescape=False,
    )
    tmpl = env.get_template(_TEMPLATE_NAME)
    body = tmpl.render(**data)
    from cutora.ui.theme.states import render_states
    extra = render_states(data)
    header = (
        "/* Generated by tools/build_qss.py — do not edit by hand. */\n"
        "/* Source: cutora/ui/theme/theme_dark.qss.j2 + tokens.py + states.py */\n\n"
    )
    return header + body + "\n" + extra
