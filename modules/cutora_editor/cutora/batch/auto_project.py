def parse_table_titles(txt_path: str) -> dict[str, str]:
    if not txt_path or not os.path.isfile(txt_path):
        return {}
    raw = open(txt_path, "r", encoding="utf-8").read()
    titles: dict[str, str] = {}
    pattern = re.compile(
        r"https://drive\.google\.com/drive/folders/[A-Za-z0-9_-]+[^\t]*\t(v\d+)\t(.*?)\thttps://drive\.google\.com/[^\t]+\t",
        re.DOTALL,
    )
    for m in pattern.finditer(raw):
        vid = m.group(1).strip()
        t = m.group(2).strip()
        if t.startswith('"') and t.endswith('"'):
            t = t[1:-1].strip()
        t = re.sub(r"\s+", " ", t).strip()
        titles[vid] = t
    if not titles:
        for line in raw.splitlines():
            parts = line.split("\t")
            if len(parts) >= 2 and re.match(r"^v\d+$", parts[0].strip()):
                titles[parts[0].strip()] = parts[1].strip().strip('"')
    return titles


def load_clips_mapping(manifest_or_dir: str) -> dict[str, list[str]]:
    if os.path.isfile(manifest_or_dir):
        manifest_path = manifest_or_dir
        clips_dir = os.path.join(os.path.dirname(manifest_path), "clips")
    else:
        cand_m = os.path.join(manifest_or_dir, "manifest.json")
        if os.path.isfile(cand_m):
            manifest_path = cand_m
            clips_dir = os.path.join(manifest_or_dir, "clips")
        else:
            manifest_path = ""
            clips_dir = manifest_or_dir

    mapping: dict[str, list[tuple[int, str]]] = {}
    if manifest_path and os.path.isfile(manifest_path):
        manifest = json.load(open(manifest_path, "r", encoding="utf-8"))
        batch_prefix = os.path.basename(os.path.dirname(manifest_path)).split("-")[0]
        for item in manifest.get("items", []):
            src = str(item.get("source_image") or "")
            stem = os.path.splitext(os.path.basename(src))[0]
            m = re.match(r"^(v\d+)\((\d+)\)$", stem)
            if not m:
                continue
            vid = m.group(1)
            idx = int(m.group(2))
            sid = str(item.get("id") or "")
            p_idx = int(sid[1:]) if sid.startswith("s") and sid[1:].isdigit() else idx
            clip_name = f"{batch_prefix}-{sid}-p{p_idx:02d}.mp4"
            clip_path = os.path.join(clips_dir, clip_name)
            if not os.path.isfile(clip_path):
                # 兜底按 sid 搜索
                for fn in os.listdir(clips_dir) if os.path.isdir(clips_dir) else []:
                    if f"-{sid}-" in fn and fn.endswith(".mp4"):
                        clip_path = os.path.join(clips_dir, fn)
                        break
            if os.path.isfile(clip_path):
                mapping.setdefault(vid, []).append((idx, clip_path))
    elif os.path.isdir(clips_dir):
        for fn in sorted(os.listdir(clips_dir)):
            if not fn.lower().endswith(".mp4"):
                continue
            m = re.match(r"^(v\d+)\((\d+)\)\.mp4$", fn, re.IGNORECASE)
            if m:
                mapping.setdefault(m.group(1).lower(), []).append((int(m.group(2)), os.path.join(clips_dir, fn)))

    out: dict[str, list[str]] = {}
    for vid, lst in mapping.items():
        lst.sort(key=lambda x: x[0])
        out[vid] = [p for _, p in lst]
    return out


def build_batch_project(
    *,
    batch_dir: str,
    videos_dir: str,
    clips_manifest: str,
    table_path: str = "",
    phone_img: str = "",
    project_name: str = "",
    export_dest: str = "",
    parts: int = 2,
    ref_project: str = r"D:\1_PROJECT\2026-10-19\A\2026-10-19A.cutora",
) -> dict:
    from cutora.asr.clip_worker import AsrClient
    from cutora.batch import cli
    from cutora.batch import link_import as LI
    from cutora.batch import script_insert_image as SII
    from cutora.batch import text_batch as TB
    from cutora.batch import text_locate_asr as LOC_ASR
    from cutora.batch import title_align
    from cutora.model.project_schema import PERSIST_UNDERSCORE_KEYS
    from cutora.model.timeline_model import Track
    from cutora.ui import main_window as host

    cli.ensure_qapp()

    titles = parse_table_titles(table_path)
    mapping = load_clips_mapping(clips_manifest)

    video_files = []
    for fn in os.listdir(videos_dir):
        m = re.match(r"^(v\d+)\.mp4$", fn, re.IGNORECASE)
        if m:
            vid = m.group(1).lower()
            vnum = int(vid[1:])
            video_files.append((vnum, vid, os.path.join(videos_dir, fn)))
    video_files.sort(key=lambda x: x[0])

    ref_title_ov = copy.deepcopy(DEFAULT_TITLE_OVERLAY_TEMPLATE)
    ref_ai_ov = copy.deepcopy(DEFAULT_AI_OVERLAY_TEMPLATE)
    if ref_project and os.path.isfile(ref_project):
        try:
            rp = json.load(open(ref_project, "r", encoding="utf-8"))
            rt = rp["tasks"][min(2, len(rp["tasks"]) - 1)]
            if rt.get("text_overlays"):
                ref_title_ov = copy.deepcopy(rt["text_overlays"][0])
            if len(rt.get("text_overlays") or []) >= 2:
                ref_ai_ov = copy.deepcopy(rt["text_overlays"][1])
        except Exception:
            pass

    if not export_dest:
        export_dest = os.path.join(batch_dir, "成品").replace("\\", "/")
    if not project_name:
        project_name = os.path.basename(os.path.normpath(batch_dir))

    win_start, win_end = 0.0, 25.0
    need_asr = []
    for _, vid, vpath in video_files:
        words, sents, _ = LOC_ASR.lookup_best(vpath, win_start, win_end, "en")
        if not words:
            need_asr.append((vid, vpath))

    if need_asr:
        client = AsrClient()
        try:
            client.start("en")
            for vid, vpath in need_asr:
                words, sents = LOC_ASR._transcribe_window(client, vpath, "en", win_start, win_end)
                LOC_ASR.store(vpath, words, win_start, win_end, "en", sentences=sents)
        finally:
            try:
                client.close()
            except Exception:
                pass

    tasks = []
    replaced_titles = {}
    for idx, (_, vid, vpath) in enumerate(video_files):
        orig_title = titles.get(vid, "")
        clips = mapping.get(vid, [])
        words, sents, _ = LOC_ASR.lookup_best(vpath, win_start, win_end, "en")
        words = words or []
        sents = sents or []

        used_title = orig_title
        replaced = False
        if orig_title:
            loc = TB.locate_text(words, orig_title)
            if loc.get("ok") and loc.get("end"):
                title_end = float(loc["end"])
            else:
                sents_timed = title_align.sentences_with_times(words, sents)
                rep = title_align.replacement_title(orig_title, sents_timed)
                if rep:
                    used_title = rep
                    replaced = True
                    replaced_titles[vid] = {"orig": orig_title, "replaced": used_title}
                    loc2 = TB.locate_text(words, used_title)
                    if loc2.get("ok") and loc2.get("end"):
                        title_end = float(loc2["end"])
                    else:
                        title_end = float(sents_timed[0]["end"]) if sents_timed else 4.0
                else:
                    title_end = float(sents[0]["end"]) if sents else 4.0
        else:
            sents_timed = title_align.sentences_with_times(words, sents)
            used_title = sents_timed[0]["text"] if sents_timed else vid
            title_end = float(sents_timed[0]["end"]) if sents_timed else 4.0

        title_end = round(max(1.8, min(title_end, 18.0)), 3)

        t = cli.make_task_from_video(host, vpath, text="")
        t["_export_dest_folder"] = export_dest
        t["_player_ms"] = 0
        t["z_order_v2"] = True
        t["_title_locate"] = {
            "window": [win_start, win_end],
            "segments": words,
            "sentences": sents,
        }

        if clips:
            LI.apply_plan(
                [{"task_index": 0, "groups": [[cp] for cp in clips]}],
                [t],
                host=host,
                loop=True,
                match_duration=True,
                mute=True,
                split_layout=None,
                log=None,
            )

        tw, th = int(t["dims"][0]), int(t["dims"][1])
        scale_factor = float(tw) / 1080.0
        dur = float(t["duration"])
        tl = t["timeline"]

        text_tr = host.get_or_create_track(tl, "text")
        ov_title = copy.deepcopy(ref_title_ov)
        ov_title["content"] = used_title
        ov_title["start"] = 0.0
        ov_title["end"] = title_end
        ov_title["fontsize"] = max(18, int(round(44 * scale_factor)))
        ov_title["x"] = 0.0
        ov_title["w"] = float(tw)
        ov_title["_canvas_w"] = tw
        ov_title["_canvas_h"] = th
        ov_title["id"] = int(time.time() * 1000000) + idx * 2
        ov_title["_track_id"] = text_tr.id
        TB.fit_box_to_text(ov_title, tw, th)
        while float(ov_title["h"]) > 290.0 * (float(th) / 1920.0) and ov_title["fontsize"] > 32:
            ov_title["fontsize"] -= 2
            TB.fit_box_to_text(ov_title, tw, th)

        ai_tr = Track("text")
        tl.add_track(ai_tr)
        ov_ai = copy.deepcopy(ref_ai_ov)
        ov_ai["start"] = 0.0
        ov_ai["end"] = dur
        ov_ai["_canvas_w"] = tw
        ov_ai["_canvas_h"] = th
        ov_ai["_track_id"] = ai_tr.id
        ov_ai["id"] = f"ov_ai_{vid}_{idx}"

        t["text_overlays"] = [ov_title, ov_ai]

        if phone_img and os.path.isfile(phone_img):
            img_tr = SII.ensure_image_track(tl, 1)
            iw, ih = 2078, 644
            el_w = 1053.1975155279504 * (float(tw) / 1080.0)
            el_h = 326.40000000000003 * (float(th) / 1920.0)
            el_x = (float(tw) - el_w) / 2.0
            el_y = 860.684785615491 * (float(th) / 1920.0)
            ov_img = {
                "type": "image",
                "start": title_end,
                "end": dur,
                "x": 0,
                "y": 0,
                "w": tw,
                "h": th,
                "rotation": 0,
                "opacity": 255,
                "elements": [
                    {
                        "kind": "image",
                        "path": phone_img,
                        "x": float(el_x),
                        "y": float(el_y),
                        "w": float(el_w),
                        "h": float(el_h),
                        "rotation": 0.0,
                        "opacity": 255.0,
                        "blend_mode": "normal",
                        "lock_aspect": True,
                        "id": uuid.uuid4().hex,
                    }
                ],
                "scale": 1.0,
                "flip_x": False,
                "flip_y": False,
                "lock_aspect": True,
                "keep_aspect": True,
                "aspect_ratio": float(iw) / float(ih),
                "blend_mode": "normal",
                "anim_in": "fade",
                "anim_out": "fade",
                "transition_preset": "fade_both",
                "transition_duration": 0.35,
                "id": "ov_insert_%s" % uuid.uuid4().hex[:12],
                "track_index": 1,
                "_track_id": img_tr.id,
                "_script": "insert_image",
            }
            t["image_overlays"] = [ov_img]
            t["batch_load"] = [
                {
                    "kind": "image",
                    "start_sec": title_end,
                    "end_sec": dur,
                    "head_pad_sec": 0.0,
                    "tail_pad_sec": 0.0,
                    "anim_in": "fade",
                    "anim_out": "fade",
                    "anim_dur_sec": 0.35,
                    "items": [
                        {
                            "path": phone_img,
                            "x_pct": round(el_x / float(tw) * 100.0, 4),
                            "y_pct": round(el_y / float(th) * 100.0, 4),
                            "w_pct": round(el_w / float(tw) * 100.0, 4),
                            "h_pct": round(el_h / float(th) * 100.0, 4),
                            "scale": 1.0,
                            "rotation": 0.0,
                            "opacity": 255.0,
                            "blend_mode": "normal",
                            "lock_aspect": True,
                        }
                    ],
                    "track_index": 1,
                    "overlay_id": ov_img["id"],
                }
            ]
        tasks.append(t)

    sheet_dir = os.path.join(batch_dir, "_face_safe_preview")
    fs_res = verify_and_calibrate_tasks(
        tasks,
        force_top_main_if_needed=True,
        render_contact_sheet_dir=sheet_dir,
        log=lambda s: print(s, flush=True),
    )

    def _save_proj(path: str, task_slice: list[dict]) -> str:
        proj_data = cli.serialize_project_data(host, task_slice, curr_idx=0)
        proj_data.pop("headless", None)
        proj_data["glossary"] = []
        proj_data["export_dest_folder"] = export_dest
        for raw_t, src_t in zip(proj_data["tasks"], task_slice):
            for uk in PERSIST_UNDERSCORE_KEYS:
                if uk in src_t:
                    raw_t[uk] = copy.deepcopy(src_t[uk])
        try:
            host._relativize_project_data(proj_data, path)
        except Exception:
            pass
        os.makedirs(os.path.dirname(path), exist_ok=True)
        cli.atomic_write_json(path, proj_data)
        return path

    saved_projects = []
    full_path = os.path.join(batch_dir, f"{project_name}.cutora")
    saved_projects.append(_save_proj(full_path, tasks))

    if parts and parts >= 2 and len(tasks) >= parts:
        chunk_sz = (len(tasks) + parts - 1) // parts
        for p_idx in range(parts):
            sub = tasks[p_idx * chunk_sz : (p_idx + 1) * chunk_sz]
            if not sub:
                continue
            ppath = os.path.join(batch_dir, f"{project_name}_part{p_idx + 1}.cutora")
            saved_projects.append(_save_proj(ppath, sub))

    report_path = os.path.join(batch_dir, f"{project_name}_facecheck.json")
    summary = {
        "ok": fs_res["ok_count"] == fs_res["total"],
        "total_tasks": fs_res["total"],
        "ok_count": fs_res["ok_count"],
        "replaced_titles": replaced_titles,
        "projects": saved_projects,
        "contact_sheets": fs_res["contact_sheets"],
        "report_path": report_path,
        "export_dest": export_dest,
    }
    with open(report_path, "w", encoding="utf-8") as f:
        json.dump({**summary, "details": fs_res["reports"]}, f, ensure_ascii=False, indent=2)
    return summary


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="CUTORA 无头批量建项 + 人脸与画面零穿帮核验")
    parser.add_argument("--batch-dir", required=True, help="批次根目录，如 D:\\1_PROJECT\\2026-10-19\\B")
    parser.add_argument("--videos", required=True, help="主视频目录，如 D:\\1_PROJECT\\2026-10-19\\B\\1019视频")
    parser.add_argument("--clips-manifest", required=True, help="配菜 manifest.json 路径或目录")
    parser.add_argument("--table", default="", help="表格文本路径（含 vNN 与标题）")
    parser.add_argument("--phone-img", default="", help="电话贴纸 PNG 路径")
    parser.add_argument("--project-name", default="", help="输出工程名前缀")
    parser.add_argument("--export-dest", default="", help="成品输出目录")
    parser.add_argument("--parts", type=int, default=2, help="拆分为几个分批工程（默认 2）")
    args = parser.parse_args(argv)

    res = build_batch_project(
        batch_dir=args.batch_dir,
        videos_dir=args.videos,
        clips_manifest=args.clips_manifest,
        table_path=args.table,
        phone_img=args.phone_img,
        project_name=args.project_name,
        export_dest=args.export_dest,
        parts=args.parts,
    )
    print(json.dumps(res, ensure_ascii=False), flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
