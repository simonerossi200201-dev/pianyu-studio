"""无头全自动批量建项与「人脸与画面零穿帮核验」CLI (`python -m cutora.batch.auto_project`)。

供 Robota 本地智能体或批处理脚本直接调用：
- 解析任务表格（支持 `<Drive文件夹>\t<vNN>\t<标题>\t<Drive视频>\t<文案>` 或 `<vNN>\t<标题>`）；
- 自动扫描主视频目录与 Orante `manifest.json` / `clips` 配菜片段；
- 通过 Whisper ASR 定位每条主视频开头口播标题结束时间 `title_end`，若表格标题与原视频口播不符则自动替换为原视频真实口播首句（保持原句时间戳）；
- 自动插入电话贴纸（`title_end` ~ 视频结束）与 AI 署名（全程）；
- 自动分配多样化弧线/斜切分屏样式，并执行 `cutora.batch.face_safe` 人脸与画面零穿帮自动校准 + 双阶段实景渲染抽帧复核；
- 支持自动拆分为 1 个或 N 个分批工程（如 `_part1.cutora`、`_part2.cutora`）。
"""
