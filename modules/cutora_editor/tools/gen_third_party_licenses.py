def _icons() -> str:
    lines = ["## Icons", ""]
    if os.path.isfile(ICON_MANIFEST):
        with open(ICON_MANIFEST, "r", encoding="utf-8") as f:
            data = json.load(f)
        lines.append("| File | Origin |")
        lines.append("|---|---|")
        for item in data.get("icons") or []:
            lines.append("| %s | %s |" % (item.get("file"), item.get("origin")))
        lines.append("")
    lines.append("See `resources/icons/LICENSE`. Lucide (ISC) SVGs are vendored under `resources/icons/lucide/`.")
    lines.append("")
    return "\n".join(lines)


