def _cell(value) -> str:
    text = str(value or "").replace("\r", " ").replace("\n", " ").replace("|", "/")
    return "".join(ch if (ch == "\t" or ord(ch) >= 32) else " " for ch in text).strip()


def _safe_filename(name: str, version: str) -> str:
    stem = "%s-%s" % (name, version)
    out = []
    for ch in stem:
        if ch.isalnum() or ch in "._-":
            out.append(ch)
        else:
            out.append("_")
    return "".join(out) + ".txt"


def _printable(text: str) -> str:
    return "".join(ch if (ch in "\t\n\r" or ord(ch) >= 32) else " " for ch in text)


def _looks_like_license(text: str) -> bool:
    if not text or not text.strip():
        return False
    raw = text.encode("utf-8", "replace")
    if len(raw) > MAX_LICENSE_BYTES:
        return False
    ctrl = sum(1 for ch in text if ord(ch) < 32 and ch not in "\t\n\r")
    if ctrl > 8:
        return False
    lower = text.lower()
    needles = (
        "permission is hereby granted",
        "apache license",
        "gnu lesser general public",
        "gnu general public",
        "bsd ",
        "redistribution and use",
        "mozilla public license",
        "isc license",
        "mit license",
        "licensed under",
        "copyright",
        "all rights reserved",
        "creative commons",
    )
    return any(n in lower for n in needles)


def _override_text(name: str, version: str, spdx: str, source: str, extra_file: str = "") -> str:
    candidates = []
    if extra_file:
        candidates.append(os.path.join(OVERRIDE_DIR, extra_file))
    candidates.append(os.path.join(OVERRIDE_DIR, _safe_filename(name, version)))
    body = ""
    for path in candidates:
        if os.path.isfile(path):
            body = open(path, encoding="utf-8").read()
            break
    header = (
        "Provenance: %s %s is %s.\n"
        "Text taken from %s — not inferred from the wheel filename.\n\n"
        % (name, version, spdx, source)
    )
    return header + body


def _write_license_file(name: str, version: str, text: str) -> str:
    os.makedirs(LIC_DIR, exist_ok=True)
    fname = _safe_filename(name, version)
    path = os.path.join(LIC_DIR, fname)
    cleaned = _printable(text).replace("\r\n", "\n").replace("\r", "\n")
    if not cleaned.endswith("\n"):
        cleaned += "\n"
    raw = cleaned.encode("utf-8")
    if len(raw) > MAX_LICENSE_BYTES:
        raise SystemExit("license text too large for %s: %d" % (fname, len(raw)))
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(cleaned)
    return "resources/licenses/" + fname


def _pip_licenses() -> str:
    exe = sys.executable
    r = subprocess.run(
        [exe, "-m", "piplicenses", "--format=json", "--with-urls", "--with-license-file"],
        cwd=REPO,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    if r.returncode != 0 or not (r.stdout or "").strip():
        raise SystemExit("pip-licenses produced no output: %s" % (r.stderr or r.returncode))
    rows = json.loads(r.stdout)
    if not isinstance(rows, list):
        raise SystemExit("pip-licenses JSON was not a list")

    old = {}
    if os.path.isdir(LIC_DIR):
        for fn in os.listdir(LIC_DIR):
            old[fn] = os.path.join(LIC_DIR, fn)

    lines = [
        "| Name | Version | License | URL | License file |",
        "|---|---|---|---|---|",
    ]
    keep = set()
    for row in sorted(rows, key=lambda x: _cell((x or {}).get("Name")).lower()):
        if not isinstance(row, dict):
            continue
        name = _cell(row.get("Name"))
        version = _cell(row.get("Version"))
        spdx = _cell(row.get("License"))
        url = _cell(row.get("URL"))
        key = (name.lower(), version)
        override = LICENSE_OVERRIDES.get(key) or LICENSE_OVERRIDES.get((name.lower(),))
        if override:
            spdx = override["license"]
            text = _override_text(
                name, version, spdx, override["source"],
                extra_file=str(override.get("file") or ""),
            )
        else:
            text = str(row.get("LicenseText") or "")
            if not _looks_like_license(text):
                text = (
                    "License identifier from the wheel: %s\n"
                    "Project URL: %s\n"
                    "The wheel did not ship a recognizable LICENSE file. "
                    "See the project URL for the official text.\n"
                    % (spdx or "(none)", url or "(none)")
                )
        rel = _write_license_file(name, version, text)
        keep.add(os.path.basename(rel))
        lines.append("| %s | %s | %s | %s | `%s` |" % (
            name, version, spdx, url, rel,
        ))
    for fn, path in old.items():
        if fn not in keep and os.path.isfile(path):
            os.remove(path)
    return "\n".join(lines)


def _fonts() -> str:
    lines = ["## Fonts", ""]
    if not os.path.isfile(MANIFEST):
        lines.append("_FONTS_MANIFEST.json missing — run tools/font_audit.py_")
        lines.append("")
        return "\n".join(lines)
    with open(MANIFEST, "r", encoding="utf-8") as f:
        data = json.load(f)
    lines.append("Count: **%s**. By license: `%s`." % (data.get("font_count"), data.get("by_license")))
    lines.append("")
    lines.append("| Family | License | File |")
    lines.append("|---|---|---|")
    seen = set()
    for item in data.get("fonts") or []:
        fam = item.get("family") or ""
        if fam in seen:
            continue
        seen.add(fam)
        lines.append("| %s | %s | %s |" % (fam, item.get("license"), item.get("file")))
    lines.append("")
    q = data.get("quarantined") or []
    if q:
        lines.append("Quarantined (not shipped in the font manager):")
        for item in q:
            lines.append("- %s (%s)" % (item.get("file"), item.get("license")))
        lines.append("")
    return "\n".join(lines)


