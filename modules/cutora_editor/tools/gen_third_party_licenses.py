    parts = [
        HEADER,
        "## Python packages",
        "",
        _pip_licenses(),
        "",
        QT_LGPL,
        CPYTHON,
        WHISPERX,
        TAPNEXT,
        MODELS,
        _fonts(),
        _icons(),
        _stickers(),
        _brand(),
        "## Audio",
        "",
        "SFX WAV files under `resources/audio/sfx/` are generated by `cutora/audio/sfx_synth.py`.",
        "IR WAV files under `resources/audio/ir/` are generated by `cutora/audio/spatial_ir.py`.",
        "Neither directory contains third-party recordings.",
        "",
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(parts).replace("\n\n\n", "\n\n"))
    n = os.path.getsize(OUT)
    with open(OUT, "r", encoding="utf-8") as f:
        nlines = sum(1 for _ in f)
    print("wrote", OUT, "bytes=%d lines=%d" % (n, nlines))
    return 0


