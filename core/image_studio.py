def _make_item_dict(
    idx: int,
    prompt: str,
    aspect: str = "9:16",
    engine: str = "flux2",
    seed: int = 0,
    typography: Optional[dict[str, Any]] = None,
    item_id: str = "",
) -> dict[str, Any]:
    aspect_clean = aspect if aspect in ASPECT_PRESETS else "9:16"
    w, h = ASPECT_PRESETS[aspect_clean]
    iid = item_id or f"img_{idx:04d}"
    if seed <= 0:
        h_val = int(hashlib.sha1(f"{iid}:{prompt}:{aspect_clean}".encode("utf-8")).hexdigest()[:8], 16)
        seed = 100000 + (h_val % 899999)
    typo = dict(DEFAULT_TYPOGRAPHY)
    if typography:
        typo.update(typography)
    return {
        "id": iid,
        "index": idx,
        "prompt": (prompt or "").strip(),
        "aspect": aspect_clean,
        "width": w,
        "height": h,
        "seed": int(seed),
        "engine": engine or "flux2",
        "status": "draft",
        "review": "pending",
        "rating": 0,
        "raw_file": f"raw/{iid}.png",
        "matted_file": "",
        "composed_file": f"composed/{iid}_final.png",
        "mtime": _now_ms(),
        "faces": [],
        "qc": {"ok": True, "issues": [], "sharpness": 0.0, "brightness": 0.0, "face_overlap": False},
        "typography": typo,
        "history": [],
    }


