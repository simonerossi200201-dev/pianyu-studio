# E. 一键移交 Orante 制片台任务 (Handoff to Orante Task)
# ============================================================================
def _resolve_orante_task_dir(task_id_or_dir: str | Path, proj_dir: Path) -> tuple[str, Path]:
    """根据传入的目录路径或任务 ID (如 `T0136`) 解析目标 Orante 任务目录。"""
    s = str(task_id_or_dir or "").strip()
    if not s:
        target = proj_dir / "orante_handoff" / "T0001-ImageStudio"
        return "T0001", target

    cand = Path(s)
    # 如果包含路径分隔符或本身是已存在的目录
    if cand.is_dir() or "\\" in s or "/" in s or ":" in s:
        m_tid = re.match(r"^(T\d{3,6})", cand.name, re.IGNORECASE)
        tid = m_tid.group(1).upper() if m_tid else "T0001"
        return tid, cand.resolve()

    # 若传入形如 T0136 的任务 ID，先查 orante.db
    tid = s.upper() if re.match(r"^T\d+$", s, re.IGNORECASE) else "T0001"
    orante_db = LTX_ROOT / "modules" / "orante_desk" / "data" / "orante.db"
    if orante_db.is_file():
        try:
            with sqlite3.connect(str(orante_db)) as conn:
                row = conn.execute("SELECT dir FROM tasks WHERE id=? LIMIT 1", (tid,)).fetchone()
                if row and row[0]:
                    return tid, Path(row[0]).resolve()
        except Exception:
            pass

    # 搜索 D:\1_PROJECT 下的 Txxxx-* 目录
    proj_root = Path(r"D:\1_PROJECT")
    if proj_root.is_dir():
        matches = sorted(proj_root.glob(f"*/*/{tid}*"))
        if matches:
            return tid, matches[-1].resolve()

    return tid, (proj_dir / "orante_handoff" / f"{tid}-ImageStudio").resolve()


def export_to_orante_task(
    proj_dir: str | Path,
    task_id_or_dir: str | Path,
    item_ids: Optional[list[str]] = None,
    use_composed: bool = False,
) -> dict[str, Any]:
    """
    将选中的（或全部非淘汰 `review != "rejected"`）图片移交至目标 Orante 任务：
    - 默认拷贝干净的 `raw_file`（防止图生视频 I2V 把静态文字变形成乱码），若 `use_composed=True` 则拷贝带字合成图 `composed_file`；
    - 按 `images/p01.png`, `p02.png`... 标准序号写入；
    - 自动创建或更新 `<task_dir>/manifest.json`（100% 兼容 Orante v2 `Manifest` 结构）。
    """
    p = ensure_project_dirs(proj_dir)
    data = load_project(p)
    items = data.get("items") or []

    if item_ids:
        id_set = set(item_ids)
        selected = [it for it in items if it.get("id") in id_set]
    else:
        only_sel = [it for it in items if it.get("review") == "selected"]
        selected = only_sel if only_sel else [it for it in items if it.get("review") != "rejected"]

    tid, task_dir = _resolve_orante_task_dir(task_id_or_dir, p)
    img_dir = task_dir / "images"
    img_dir.mkdir(parents=True, exist_ok=True)
    (task_dir / "clips").mkdir(parents=True, exist_ok=True)

    manifest_path = task_dir / "manifest.json"
    existing_manifest: dict[str, Any] = {}
    if manifest_path.is_file():
        try:
            existing_manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        except Exception:
            existing_manifest = {}

    manifest_images: list[dict[str, Any]] = []
    manifest_segments: list[dict[str, Any]] = []
    exported_files: list[str] = []

    for idx, it in enumerate(selected, 1):
        p_code = f"p{idx:02d}"
        rel_src = it.get("composed_file") if use_composed else it.get("raw_file")
        src_abs = p / str(rel_src or it.get("raw_file"))
        if not src_abs.is_file():
            src_abs = p / str(it.get("raw_file"))
        if not src_abs.is_file():
            continue

        dst_rel = f"images/{p_code}.png"
        dst_abs = task_dir / dst_rel
        shutil.copy2(src_abs, dst_abs)
        sha1_hex = hashlib.sha1(dst_abs.read_bytes()).hexdigest()
        prompt_desc = str(it.get("prompt") or "").strip()

        manifest_images.append({
            "p": p_code,
            "file": dst_rel,
            "sha1": sha1_hex,
            "role": "主体",
            "status": "ok",
            "desc": prompt_desc,
            "voice": "",
            "desc_manual": bool(prompt_desc),
            "voice_manual": False,
            "desc_stale": False,
            "eye": "闭眼",
            "scene": "常规",
            "measure": {"width": it.get("width", 1088), "height": it.get("height", 1920), "aspect": it.get("aspect", "9:16")},
            "origin": "local",
            "src": it.get("id", p_code),
            "pose": {},
        })
        manifest_segments.append({
            "s": idx,
            "text": str((it.get("typography") or {}).get("title") or prompt_desc),
            "duration": 6,
            "image": p_code,
            "role": "主体",
            "shot": "",
            "prompt_final": prompt_desc,
            "status": "planned",
            "gen_id": None,
            "takes": [],
            "error": None,
            "bridge": {},
        })
        exported_files.append(str(dst_abs))

    copy_text = "\n".join([sg["text"] for sg in manifest_segments if sg.get("text")])
    manifest_data = {
        "version": 2,
        "task_id": existing_manifest.get("task_id") or tid,
        "name": existing_manifest.get("name") or task_dir.name,
        "engine": existing_manifest.get("engine") or "flow",
        "account": existing_manifest.get("account") or "Flow1",
        "type": existing_manifest.get("type") or "long",
        "copy": existing_manifest.get("copy") or {
            "text": copy_text,
            "sha1": hashlib.sha1(copy_text.encode("utf-8")).hexdigest(),
        },
        "images": manifest_images,
        "split": existing_manifest.get("split") or {"rule": {"source": "image_studio"}},
        "segments": manifest_segments,
        "track": existing_manifest.get("track") or {
            "pins": {},
            "pools": [],
            "hold": 3,
            "jitter": 1,
            "unit": "seg",
            "seed": None,
        },
        "prompts_snapshot": existing_manifest.get("prompts_snapshot") or {},
        "gapfill": existing_manifest.get("gapfill") or {},
        "mode": existing_manifest.get("mode") or "first_frame",
        "chain": existing_manifest.get("chain") or {},
    }

    manifest_path.write_text(json.dumps(manifest_data, ensure_ascii=False, indent=2), encoding="utf-8")
    return {
        "ok": True,
        "task_id": manifest_data["task_id"],
        "task_dir": str(task_dir),
        "manifest_path": str(manifest_path),
        "exported_count": len(exported_files),
        "exported_files": exported_files,
        "use_composed": use_composed,
    }


