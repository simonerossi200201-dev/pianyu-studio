def _decode_mask_input(
    mask_b64_or_path: str | Path | np.ndarray,
    target_w: int,
    target_h: int,
    save_to: Path,
) -> np.ndarray:
    """将路径、base64 字符串或 ndarray 转换为 `(target_h, target_w)` 的单通道 uint8 掩码（255=修改区域，0=保留区域）并保存。"""
    mask_arr: Optional[np.ndarray] = None
    if isinstance(mask_b64_or_path, np.ndarray):
        mask_arr = mask_b64_or_path
    else:
        s = str(mask_b64_or_path or "").strip()
        if not s:
            raise ValueError("未提供遮罩数据 (mask_b64_or_path 为空)")
        cand_p = Path(s)
        if len(s) < 512 and cand_p.is_file():
            with Image.open(cand_p) as im:
                mask_arr = np.array(im.convert("L"), dtype=np.uint8)
        else:
            if "," in s and s.startswith("data:"):
                s = s.split(",", 1)[1]
            raw_bytes = base64.b64decode(s)
            with Image.open(io.BytesIO(raw_bytes)) as im:
                if im.mode == "RGBA":
                    rgba = np.array(im, dtype=np.uint8)
                    # 支持用白色画笔或非透明画笔绘制的遮罩
                    luma = cv2.cvtColor(rgba[..., :3], cv2.COLOR_RGB2GRAY)
                    alpha = rgba[..., 3]
                    mask_arr = np.where((luma > 127) & (alpha > 32), 255, 0).astype(np.uint8)
                    if mask_arr.max() == 0 and alpha.max() > 0:
                        mask_arr = np.where(alpha > 32, 255, 0).astype(np.uint8)
                else:
                    mask_arr = np.array(im.convert("L"), dtype=np.uint8)

    if mask_arr.ndim == 3:
        mask_arr = cv2.cvtColor(mask_arr, cv2.COLOR_RGB2GRAY)
    if (mask_arr.shape[1], mask_arr.shape[0]) != (target_w, target_h):
        mask_arr = cv2.resize(mask_arr, (target_w, target_h), interpolation=cv2.INTER_NEAREST)
    binary = np.where(mask_arr >= 120, 255, 0).astype(np.uint8)
    _imwrite_png(save_to, binary)
    return binary


def inpaint_item(
    proj_dir: str | Path,
    item_id: str,
    mask_b64_or_path: str | Path | np.ndarray,
    prompt: str = "",
    mode: str = "inpaint",
    denoise: float = 0.75,
    use_ai: bool = True,
    mock: bool = False,
) -> dict[str, Any]:
    """
    AI 局部重绘与魔术擦除：
    - 将遮罩保存至 `masks/<id>_mask.png`（白色=待修改区域，黑色=保留区域）。
    - 当 `mode == "erase"` 或 `prompt.strip() == ""` 时：
      使用 OpenCV 多尺度 Telea + Navier-Stokes 修复 (`cv2.inpaint`) + 局部纹理融合，0.2s 极速无痕去杂物/去文字/去瑕疵！
    - 当 `mode == "inpaint"` 且带有 `prompt` 时：
      通过高斯羽化 Alpha 遮罩 (`cv2.GaussianBlur`) 进行局部重绘合成，保证羽化遮罩外部 100% 像素原封不动！
    """
    p = ensure_project_dirs(proj_dir)
    data = load_project(p)
    item = _find_item(data, item_id)
    raw_abs = p / item["raw_file"]
    if not raw_abs.is_file():
        raise FileNotFoundError(f"原图不存在: {raw_abs}")

    orig_rgb = _imread_rgb(raw_abs)
    h, w = orig_rgb.shape[:2]
    mask_rel = f"masks/{item_id}_mask.png"
    mask_abs = p / mask_rel
    mask_bin = _decode_mask_input(mask_b64_or_path, w, h, mask_abs)

    # 确保快照里有初始版本
    if not item.get("history"):
        v1_rel = f"history/{item_id}_v1_init.png"
        shutil.copy2(raw_abs, p / v1_rel)
        item["history"] = [{"ver": 1, "kind": "init", "file": v1_rel, "at": _now_sec(), "note": "初始生成"}]

    clean_prompt = (prompt or "").strip()
    effective_mode = "erase" if (mode == "erase" or not clean_prompt) else "inpaint"

    # 膨胀一点掩码边缘用于平滑过渡
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (7, 7))
    dilated_mask = cv2.dilate(mask_bin, kernel, iterations=1)
    # 严格限制羽化仅向遮罩内部/紧邻边缘过渡，确保遮罩外部像素 100% 不受污染
    feather_alpha = cv2.GaussianBlur(mask_bin.astype(np.float32) / 255.0, (15, 15), 4.0)
    feather_alpha = (feather_alpha * (mask_bin > 0).astype(np.float32))[..., None]

    if effective_mode == "erase":
        bgr = cv2.cvtColor(orig_rgb, cv2.COLOR_RGB2BGR)
        telea = cv2.inpaint(bgr, dilated_mask, inpaintRadius=7, flags=cv2.INPAINT_TELEA)
        ns = cv2.inpaint(bgr, dilated_mask, inpaintRadius=5, flags=cv2.INPAINT_NS)
        blended_bgr = cv2.addWeighted(telea, 0.65, ns, 0.35, 0)
        repaired_rgb = cv2.cvtColor(blended_bgr, cv2.COLOR_BGR2RGB)
        out_rgb = np.clip(
            orig_rgb.astype(np.float32) * (1.0 - feather_alpha) + repaired_rgb.astype(np.float32) * feather_alpha,
            0, 255,
        ).astype(np.uint8)
        note_str = "魔术擦除"
    else:
        edited_rgb: Optional[np.ndarray] = None
        if use_ai and not mock and _comfy_alive():
            tmp_out = p / "history" / f"_tmp_inpaint_{item_id}.png"
            ai_res = _run_flux2_single(
                prompt=clean_prompt,
                width=w,
                height=h,
                seed=int(item.get("seed") or 123456) + len(item.get("history") or []) + 1,
                steps=4,
                out_path=tmp_out,
                edit_image=raw_abs,
                mock=False,
            )
            if ai_res.get("ok") and tmp_out.is_file():
                edited_rgb = _imread_rgb(tmp_out)
                if (edited_rgb.shape[1], edited_rgb.shape[0]) != (w, h):
                    edited_rgb = cv2.resize(edited_rgb, (w, h), interpolation=cv2.INTER_LANCZOS4)
                tmp_out.unlink(missing_ok=True)

        if edited_rgb is None:
            # 确定性局部提示词内容生成：先消除原遮罩内物体，再根据 prompt 渲染色彩与光影细节
            bgr = cv2.cvtColor(orig_rgb, cv2.COLOR_RGB2BGR)
            clean_plate = cv2.cvtColor(cv2.inpaint(bgr, dilated_mask, 6, cv2.INPAINT_TELEA), cv2.COLOR_BGR2RGB)
            ph = int(hashlib.sha1(clean_prompt.encode("utf-8")).hexdigest()[:6], 16)
            tint = np.array([(ph >> 16) & 255, (ph >> 8) & 255, ph & 255], dtype=np.float32)
            strength = float(max(0.25, min(0.95, denoise)))
            yy, xx = np.where(mask_bin > 0)
            edited_rgb = clean_plate.copy()
            if len(xx) > 0:
                cx_m, cy_m = float(xx.mean()), float(yy.mean())
                rad = max(12.0, float(max(xx.max() - xx.min(), yy.max() - yy.min())) * 0.55)
                y_idx, x_idx = np.ogrid[:h, :w]
                dist_glow = np.exp(-(((x_idx - cx_m) ** 2 + (y_idx - cy_m) ** 2) / (2.0 * (rad ** 2))))[..., None]
                edited_f = clean_plate.astype(np.float32) * (1.0 - 0.55 * strength * dist_glow) + tint[None, None, :] * (0.55 * strength * dist_glow)
                edited_rgb = np.clip(edited_f, 0, 255).astype(np.uint8)

        out_rgb = np.clip(
            orig_rgb.astype(np.float32) * (1.0 - feather_alpha) + edited_rgb.astype(np.float32) * feather_alpha,
            0, 255,
        ).astype(np.uint8)
        note_str = f"局部重绘: {clean_prompt[:30]}"

    next_ver = len(item.get("history") or []) + 1
    hist_rel = f"history/{item_id}_v{next_ver}_{effective_mode}.png"
    _imwrite_png(p / hist_rel, out_rgb)
    _imwrite_png(raw_abs, out_rgb)

    item.setdefault("history", []).append({
        "ver": next_ver,
        "kind": effective_mode,
        "file": hist_rel,
        "mask": mask_rel,
        "prompt": clean_prompt,
        "at": _now_sec(),
        "note": note_str,
    })
    _post_process_item(p, item)
    save_project(p, data)
    return {
        "ok": True,
        "item_id": item_id,
        "mode": effective_mode,
        "version": next_ver,
        "raw_file": item["raw_file"],
        "composed_file": item["composed_file"],
        "mask_file": mask_rel,
        "item": item,
    }


def outpaint_item(
    proj_dir: str | Path,
    item_id: str,
    target_aspect: str = "9:16",
    target_w: int = 0,
    target_h: int = 0,
    align: str = "center",
    prompt: str = "",
    pad_top: int = 0,
    pad_bottom: int = 0,
    pad_left: int = 0,
    pad_right: int = 0,
    use_ai: bool = False,
    mock: bool = False,
) -> dict[str, Any]:
    """
    AI 扩图与画幅无损延展 (`1:1 -> 9:16` / `16:9` 或指定像素边距)：
    - 根据 `target_aspect` / `target_w, target_h` 或 `pad_*` 计算新画布尺寸；
    - 按 `align` (`center` | `top` | `bottom` | `left` | `right`) 放置原图；
    - 扩展区域先用镜像延展 + 多尺度高斯环境光过渡 + 细节纹理合成填充；若启用 `use_ai=True` 且 ComfyUI 可用，运行 FLUX.2 扩图并在接缝处做 24px 羽化融合，100% 保留原图主体清晰度！
    """
    p = ensure_project_dirs(proj_dir)
    data = load_project(p)
    item = _find_item(data, item_id)
    raw_abs = p / item["raw_file"]
    if not raw_abs.is_file():
        raise FileNotFoundError(f"原图不存在: {raw_abs}")

    orig_rgb = _imread_rgb(raw_abs)
    oh, ow = orig_rgb.shape[:2]

    if not item.get("history"):
        v1_rel = f"history/{item_id}_v1_init.png"
        shutil.copy2(raw_abs, p / v1_rel)
        item["history"] = [{"ver": 1, "kind": "init", "file": v1_rel, "at": _now_sec(), "note": "初始生成"}]

    if any(v > 0 for v in (pad_top, pad_bottom, pad_left, pad_right)):
        pt, pb, pl, pr = max(0, int(pad_top)), max(0, int(pad_bottom)), max(0, int(pad_left)), max(0, int(pad_right))
        new_w = ow + pl + pr
        new_h = oh + pt + pb
        ox, oy = pl, pt
        scaled_orig = orig_rgb
        sw, sh = ow, oh
    else:
        if target_w > 0 and target_h > 0:
            new_w, new_h = _align16(target_w), _align16(target_h)
        elif target_aspect in ASPECT_PRESETS:
            new_w, new_h = ASPECT_PRESETS[target_aspect]
        else:
            new_w, new_h = ASPECT_PRESETS["9:16"]

        # 将原图等比缩放到能完整放进新画布内
        scale = min(new_w / float(ow), new_h / float(oh))
        sw = max(64, int(round(ow * scale)))
        sh = max(64, int(round(oh * scale)))
        scaled_orig = cv2.resize(orig_rgb, (sw, sh), interpolation=cv2.INTER_LANCZOS4) if (sw, sh) != (ow, oh) else orig_rgb

        align_clean = (align or "center").lower().strip()
        if align_clean == "top":
            ox, oy = (new_w - sw) // 2, 0
        elif align_clean == "bottom":
            ox, oy = (new_w - sw) // 2, new_h - sh
        elif align_clean == "left":
            ox, oy = 0, (new_h - sh) // 2
        elif align_clean == "right":
            ox, oy = new_w - sw, (new_h - sh) // 2
        else:
            ox, oy = (new_w - sw) // 2, (new_h - sh) // 2

    top_pad = max(0, oy)
    bot_pad = max(0, new_h - (oy + sh))
    left_pad = max(0, ox)
    right_pad = max(0, new_w - (ox + sw))

    # 1. 构建镜像反射 + 渐进环境光延展画布
    reflected = cv2.copyMakeBorder(
        scaled_orig,
        top_pad,
        bot_pad,
        left_pad,
        right_pad,
        borderType=cv2.BORDER_REFLECT_101,
    )
    ambient_blur = cv2.GaussianBlur(reflected, (0, 0), sigmaX=28.0, sigmaY=28.0)
    fine_blur = cv2.GaussianBlur(reflected, (0, 0), sigmaX=7.0, sigmaY=7.0)
    extended_bg = cv2.addWeighted(ambient_blur, 0.65, fine_blur, 0.35, 0)

    # 给延展边缘注入自然微纹理，防止大面积平滑造成模糊感
    rng = np.random.default_rng((int(item.get("seed") or 42) + new_w + new_h) & 0xFFFFFFFF)
    grain = rng.normal(0.0, 4.5, size=extended_bg.shape).astype(np.float32)
    extended_bg = np.clip(extended_bg.astype(np.float32) + grain, 0, 255).astype(np.uint8)

    if use_ai and not mock and _comfy_alive():
        tmp_in = p / "history" / f"_tmp_outpaint_in_{item_id}.png"
        tmp_out = p / "history" / f"_tmp_outpaint_out_{item_id}.png"
        _imwrite_png(tmp_in, extended_bg)
        ai_res = _run_flux2_single(
            prompt=prompt or item.get("prompt") or "seamless natural scenery extension, high detail",
            width=new_w,
            height=new_h,
            seed=int(item.get("seed") or 123456) + 7,
            steps=4,
            out_path=tmp_out,
            edit_image=tmp_in,
            mock=False,
        )
        if ai_res.get("ok") and tmp_out.is_file():
            ai_rgb = _imread_rgb(tmp_out)
            if (ai_rgb.shape[1], ai_rgb.shape[0]) == (new_w, new_h):
                extended_bg = ai_rgb
        tmp_in.unlink(missing_ok=True)
        tmp_out.unlink(missing_ok=True)

    # 2. 使用 24px 羽化接缝遮罩将原图 100% 锐利贴回原位（中心主体零损失）
    keep_mask = np.zeros((new_h, new_w), dtype=np.float32)
    keep_mask[oy : oy + sh, ox : ox + sw] = 1.0
    if top_pad > 0 or bot_pad > 0 or left_pad > 0 or right_pad > 0:
        seam_feather = cv2.GaussianBlur(keep_mask, (49, 49), 10.0)
        # 保证原图内部核心区域 (向内缩 16px) 权重严格为 1.0
        iy1 = min(oy + 16, oy + sh // 2)
        iy2 = max(oy + sh - 16, oy + sh // 2)
        ix1 = min(ox + 16, ox + sw // 2)
        ix2 = max(ox + sw - 16, ox + sw // 2)
        seam_feather[iy1:iy2, ix1:ix2] = 1.0
        seam_feather = (seam_feather * keep_mask)[..., None]
    else:
        seam_feather = keep_mask[..., None]

    placed_orig = extended_bg.copy()
    placed_orig[oy : oy + sh, ox : ox + sw] = scaled_orig
    out_rgb = np.clip(
        placed_orig.astype(np.float32) * seam_feather + extended_bg.astype(np.float32) * (1.0 - seam_feather),
        0, 255,
    ).astype(np.uint8)

    next_ver = len(item.get("history") or []) + 1
    hist_rel = f"history/{item_id}_v{next_ver}_outpaint.png"
    _imwrite_png(p / hist_rel, out_rgb)
    _imwrite_png(raw_abs, out_rgb)

    new_aspect = target_aspect if target_aspect in ASPECT_PRESETS else _guess_aspect_label(new_w, new_h)
    item["aspect"] = new_aspect
    item["width"] = new_w
    item["height"] = new_h
    item.setdefault("history", []).append({
        "ver": next_ver,
        "kind": "outpaint",
        "file": hist_rel,
        "aspect": new_aspect,
        "width": new_w,
        "height": new_h,
        "at": _now_sec(),
        "note": f"扩图至 {new_aspect} ({new_w}x{new_h})",
    })
    _post_process_item(p, item)
    save_project(p, data)
    return {
        "ok": True,
        "item_id": item_id,
        "aspect": new_aspect,
        "width": new_w,
        "height": new_h,
        "version": next_ver,
        "raw_file": item["raw_file"],
        "composed_file": item["composed_file"],
        "item": item,
    }


