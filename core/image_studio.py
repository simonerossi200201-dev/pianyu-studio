class ImageStudioManager:
    """统一管理单个 Image Studio 工程目录的高层门面类。"""

    def __init__(self, proj_dir: str | Path = DEFAULT_WORKSPACE_ROOT, name: str = "") -> None:
        self.proj_dir = ensure_project_dirs(proj_dir)
        self.data = load_project(self.proj_dir)
        if name and self.data.get("name") != name:
            self.data["name"] = name
            self.save()

    def reload(self) -> dict[str, Any]:
        self.data = load_project(self.proj_dir)
        return self.data

    def save(self) -> Path:
        return save_project(self.proj_dir, self.data)

    @property
    def items(self) -> list[dict[str, Any]]:
        self.reload()
        return self.data.get("items") or []

    def get_item(self, item_id: str) -> dict[str, Any]:
        self.reload()
        return _find_item(self.data, item_id)

    def set_review_state(self, item_id: str, review: str = "selected", rating: Optional[int] = None) -> dict[str, Any]:
        self.reload()
        it = _find_item(self.data, item_id)
        if review in ("pending", "selected", "rejected"):
            it["review"] = review
        if rating is not None:
            it["rating"] = max(0, min(5, int(rating)))
        it["mtime"] = _now_ms()
        self.save()
        return it

    def generate_batch(
        self,
        prompts_text: str = "",
        items_spec: Optional[list[dict[str, Any]]] = None,
        aspects: Optional[list[str]] = None,
        count_per_prompt: int = 1,
        engine: str = "flux2",
        default_typography: Optional[dict[str, Any]] = None,
        run_now: bool = True,
        steps: int = 4,
        mock: bool = False,
        progress_cb: Optional[Callable[[int, int, dict[str, Any]], None]] = None,
    ) -> dict[str, Any]:
        res = generate_items(
            self.proj_dir,
            prompts_text=prompts_text,
            items_spec=items_spec,
            aspects=aspects,
            count_per_prompt=count_per_prompt,
            engine=engine,
            default_typography=default_typography,
            run_now=run_now,
            steps=steps,
            mock=mock,
            progress_cb=progress_cb,
        )
        self.reload()
        return res

