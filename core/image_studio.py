def _compute_point_guided_mask(rgb: np.ndarray, points: Optional[list[dict[str, Any]]] = None) -> np.ndarray:
    """
    快速交互式点选分割 / 主体分割算法（`< 0.25s` 响应）：
    支持归一化坐标 (`0..1`) 或像素坐标，正样本点 (`label=1`) 与负样本点 (`label=0`)。
    结合 LAB 色彩空间种子泛洪 (`cv2.floodFill`) + OpenCV `GrabCut` 边缘精细收敛 + Alpha 羽化。
    """
    h, w = rgb.shape[:2]
    work_scale = min(1.0, 512.0 / float(max(w, h)))
    sw = max(64, int(round(w * work_scale)))
    sh = max(64, int(round(h * work_scale)))
    small_rgb = cv2.resize(rgb, (sw, sh), interpolation=cv2.INTER_AREA) if work_scale < 1.0 else rgb.copy()
    small_lab = cv2.cvtColor(small_rgb, cv2.COLOR_RGB2LAB)

    gc_mask = np.full((sh, sw), cv2.GC_PR_BGD, dtype=np.uint8)
    # 四周边缘默认标为确定背景
    border_x = max(2, int(sw * 0.04))
    border_y = max(2, int(sh * 0.04))
    gc_mask[:border_y, :] = cv2.GC_BGD
    gc_mask[-border_y:, :] = cv2.GC_BGD
    gc_mask[:, :border_x] = cv2.GC_BGD
    gc_mask[:, -border_x:] = cv2.GC_BGD

    if points:
        pos_pts: list[tuple[int, int]] = []
        neg_pts: list[tuple[int, int]] = []
        for pt in points:
            raw_x = float(pt.get("x", 0.5))
            raw_y = float(pt.get("y", 0.5))
            label = int(pt.get("label", 1))
            px = int(round(raw_x * sw)) if raw_x <= 1.05 else int(round(raw_x * work_scale))
            py = int(round(raw_y * sh)) if raw_y <= 1.05 else int(round(raw_y * work_scale))
            px = max(1, min(sw - 2, px))
            py = max(1, min(sh - 2, py))
            if label == 1:
                pos_pts.append((px, py))
            else:
                neg_pts.append((px, py))

        # 对每个正样本点执行 LAB 容差泛洪提取初始连通区域
        flood_union = np.zeros((sh, sw), dtype=np.uint8)
        for px, py in pos_pts:
            ff_mask = np.zeros((sh + 2, sw + 2), dtype=np.uint8)
            cv2.floodFill(
                small_lab.copy(),
                ff_mask,
                (px, py),
                255,
                loDiff=(28, 22, 22),
                upDiff=(28, 22, 22),
                flags=4 | (255 << 8) | cv2.FLOODFILL_MASK_ONLY,
            )
            region = ff_mask[1:-1, 1:-1]
            flood_union = cv2.bitwise_or(flood_union, region)

        if np.count_nonzero(flood_union) > 16:
            gc_mask[flood_union > 0] = cv2.GC_PR_FGD

        r_seed = max(4, int(min(sw, sh) * 0.045))
        for px, py in pos_pts:
            cv2.circle(gc_mask, (px, py), r_seed, int(cv2.GC_FGD), -1)
        for px, py in neg_pts:
            cv2.circle(gc_mask, (px, py), r_seed * 2, int(cv2.GC_BGD), -1)
    else:
        # 默认中心主体矩形初始化
        rx1, ry1 = int(sw * 0.16), int(sh * 0.10)
        rx2, ry2 = int(sw * 0.84), int(sh * 0.92)
        gc_mask[ry1:ry2, rx1:rx2] = cv2.GC_PR_FGD
        gc_mask[int(sh * 0.20) : int(sh * 0.82), int(sw * 0.32) : int(sw * 0.68)] = cv2.GC_FGD

    bgd_model = np.zeros((1, 65), np.float64)
    fgd_model = np.zeros((1, 65), np.float64)
    try:
        cv2.grabCut(small_rgb, gc_mask, None, bgd_model, fgd_model, 2, cv2.GC_INIT_WITH_MASK)
    except Exception:
        pass

    fg_small = np.where((gc_mask == cv2.GC_FGD) | (gc_mask == cv2.GC_PR_FGD), 255, 0).astype(np.uint8)
    # 形态学闭运算平滑孔洞
    kern = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (5, 5))
    fg_small = cv2.morphologyEx(fg_small, cv2.MORPH_CLOSE, kern)
    fg_full = cv2.resize(fg_small, (w, h), interpolation=cv2.INTER_LINEAR) if work_scale < 1.0 else fg_small
    fg_full = cv2.GaussianBlur(fg_full, (5, 5), 1.2)
    return fg_full


def segment_points_preview(
    image_path_or_item: str | Path | dict[str, Any],
    points: list[dict[str, Any]],
    proj_dir: Optional[str | Path] = None,
) -> dict[str, Any]:
    """供 UI 画布交互式点选分割实时预览：在 `< 0.3s` 内返回点选对象的二值掩码与 PNG Base64。"""
    if isinstance(image_path_or_item, dict):
        if not proj_dir:
            raise ValueError("传入 item 字典时必须提供 proj_dir")
        img_p = Path(proj_dir) / image_path_or_item["raw_file"]
    else:
        img_p = Path(image_path_or_item)
    rgb = _imread_rgb(img_p)
    mask = _compute_point_guided_mask(rgb, points=points)
    buf = io.BytesIO()
    Image.fromarray(mask, mode="L").save(buf, format="PNG")
    b64 = base64.b64encode(buf.getvalue()).decode("ascii")
    fg_ratio = round(float(np.count_nonzero(mask >= 128)) / float(mask.size), 4)
    return {"ok": True, "width": rgb.shape[1], "height": rgb.shape[0], "foreground_ratio": fg_ratio, "mask_b64": b64}


def matte_item(
    proj_dir: str | Path,
    item_id: str,
    mode: str = "rmbg",
    points: Optional[list[dict[str, Any]]] = None,
    bg_mode: str = "transparent",
    bg_color: str = "#000000",
    prefer_fast: bool = False,
    save_project_file: bool = True,
    _item_ref: Optional[dict[str, Any]] = None,
) -> dict[str, Any]:
    """
    AI 抠图与点选分割 (`mode="rmbg"` | `mode="sam_points"`)：
    - 生成透明前景 PNG 保存至 `matted/<id>_fg.png`；
    - 若 `mode == "sam_points"`，同时将分割掩码保存至 `masks/<id>_mask.png`；
    - 若 `bg_mode` 为 `"white"`, `"black"`, `"color"`, `"blur"`，同时输出换背景版本到 `raw/` 并记录 `history`。
    """
    p = ensure_project_dirs(proj_dir)
    if _item_ref is not None:
        data = None
        item = _item_ref
    else:
        data = load_project(p)
        item = _find_item(data, item_id)

    raw_abs = p / item["raw_file"]
    if not raw_abs.is_file():
        raise FileNotFoundError(f"原图不存在: {raw_abs}")

    rgb = _imread_rgb(raw_abs)
    h, w = rgb.shape[:2]
    matted_rel = f"matted/{item_id}_fg.png"
    matted_abs = p / matted_rel
    matted_abs.parent.mkdir(parents=True, exist_ok=True)

    alpha_mask: Optional[np.ndarray] = None
    engine_used = "point_grabcut"

    if mode == "rmbg" and not prefer_fast and not points:
        rmbg_py = LTX_ROOT / "runtime" / "venv" / "Scripts" / "python.exe"
        if not rmbg_py.is_file():
            rmbg_py = Path(r"D:\0_LLM\tools\venv_rmbg\Scripts\python.exe")
        rmbg_script = LTX_ROOT / "modules" / "studio_gateway" / "runners" / "tools" / "rmbg" / "rmbg.py"
        if not rmbg_script.is_file():
            rmbg_script = Path(r"D:\0_LLM\tools\rmbg\rmbg.py")
        if rmbg_py.is_file() and rmbg_script.is_file():
            try:
                with tempfile.TemporaryDirectory(prefix="imgstudio_rmbg_") as tmp_d:
                    env = os.environ.copy()
                    env["PYTHONUTF8"] = "1"
                    env["HF_HUB_OFFLINE"] = "1"
                    proc = subprocess.run(
                        [str(rmbg_py), str(rmbg_script), str(raw_abs), str(tmp_d)],
                        capture_output=True,
                        text=True,
                        encoding="utf-8",
                        errors="replace",
                        timeout=60,
                        env=env,
                        creationflags=CREATE_NO_WINDOW,
                    )
                    nobg_files = list(Path(tmp_d).glob("*_nobg.png"))
                    if proc.returncode == 0 and nobg_files:
                        rgba_rmbg = _imread_rgba(nobg_files[0])
                        if (rgba_rmbg.shape[1], rgba_rmbg.shape[0]) != (w, h):
                            rgba_rmbg = cv2.resize(rgba_rmbg, (w, h), interpolation=cv2.INTER_LANCZOS4)
                        alpha_mask = rgba_rmbg[..., 3]
                        engine_used = "rmbg-2.0"
            except Exception as exc:
                log.warning("RMBG-2.0 调用回退至快速前景分割: %s", exc)

    if alpha_mask is None:
        alpha_mask = _compute_point_guided_mask(rgb, points=points)
        engine_used = "sam_points" if points else "fast_matte"

    if mode == "sam_points" or points:
        mask_rel = f"masks/{item_id}_mask.png"
        _imwrite_png(p / mask_rel, np.where(alpha_mask >= 120, 255, 0).astype(np.uint8))
    else:
        mask_rel = ""

    rgba_out = np.dstack([rgb, alpha_mask]).astype(np.uint8)
    _imwrite_png(matted_abs, rgba_out)
    item["matted_file"] = matted_rel

    # 可选背景替换 (`bg_mode` in "white", "black", "color", "blur")
    bg_mode_clean = (bg_mode or "transparent").lower().strip()
    if bg_mode_clean in ("white", "black", "color", "blur"):
        if not item.get("history"):
            v1_rel = f"history/{item_id}_v1_init.png"
            shutil.copy2(raw_abs, p / v1_rel)
            item["history"] = [{"ver": 1, "kind": "init", "file": v1_rel, "at": _now_sec(), "note": "初始生成"}]

        if bg_mode_clean == "white":
            bg_arr = np.full_like(rgb, 255)
        elif bg_mode_clean == "black":
            bg_arr = np.zeros_like(rgb)
        elif bg_mode_clean == "blur":
            bg_arr = cv2.GaussianBlur(rgb, (0, 0), sigmaX=22.0, sigmaY=22.0)
        else:
            hc = (bg_color or "#1A202C").lstrip("#")
            if len(hc) == 6:
                r_c, g_c, b_c = int(hc[0:2], 16), int(hc[2:4], 16), int(hc[4:6], 16)
            else:
                r_c, g_c, b_c = 26, 32, 44
            bg_arr = np.full_like(rgb, (r_c, g_c, b_c))

        a_f = (alpha_mask.astype(np.float32) / 255.0)[..., None]
        comp_rgb = np.clip(rgb.astype(np.float32) * a_f + bg_arr.astype(np.float32) * (1.0 - a_f), 0, 255).astype(np.uint8)
        next_ver = len(item.get("history") or []) + 1
        hist_rel = f"history/{item_id}_v{next_ver}_matte_bg.png"
        _imwrite_png(p / hist_rel, comp_rgb)
        _imwrite_png(raw_abs, comp_rgb)
        item.setdefault("history", []).append({
            "ver": next_ver,
            "kind": f"matte_{bg_mode_clean}",
            "file": hist_rel,
            "at": _now_sec(),
            "note": f"抠图换背景 ({bg_mode_clean})",
        })
        _post_process_item(p, item)

    item["mtime"] = _now_ms()
    if save_project_file and data is not None:
        save_project(p, data)

    return {
        "ok": True,
        "item_id": item_id,
        "engine_used": engine_used,
        "matted_file": matted_rel,
        "matted_path": str(matted_abs),
        "mask_file": mask_rel,
        "bg_mode": bg_mode_clean,
        "item": item,
    }


def upscale_item(
    proj_dir: str | Path,
    item_id: str,
    scale: int = 2,
    use_nomos: bool = False,
) -> dict[str, Any]:
    """AI 高清放大 (`scale=2` 或 `4`) 并记录版本历史。"""
    p = ensure_project_dirs(proj_dir)
    data = load_project(p)
    item = _find_item(data, item_id)
    raw_abs = p / item["raw_file"]
    if not raw_abs.is_file():
        raise FileNotFoundError(f"原图不存在: {raw_abs}")

    if not item.get("history"):
        v1_rel = f"history/{item_id}_v1_init.png"
        shutil.copy2(raw_abs, p / v1_rel)
        item["history"] = [{"ver": 1, "kind": "init", "file": v1_rel, "at": _now_sec(), "note": "初始生成"}]

    orig_rgb = _imread_rgb(raw_abs)
    oh, ow = orig_rgb.shape[:2]
    factor = max(2, min(4, int(scale or 2)))
    nw, nh = ow * factor, oh * factor

    upscaled_rgb: Optional[np.ndarray] = None
    if use_nomos:
        comfy_py = _resolve_comfy_py()
        runner = LTX_ROOT / "modules" / "studio_gateway" / "runners" / "tools" / "upscale" / "upscale_video.py"
        if not runner.is_file():
            runner = Path(r"D:\0_LLM\tools\upscale\upscale_video.py")
        if comfy_py.is_file() and runner.is_file():
            tmp_out = p / "history" / f"_tmp_nomos_{item_id}.png"
            try:
                proc = subprocess.run(
                    [str(comfy_py), str(runner), str(raw_abs), str(tmp_out)],
                    capture_output=True,
                    text=True,
                    encoding="utf-8",
                    errors="replace",
                    timeout=120,
                    creationflags=CREATE_NO_WINDOW,
                )
                if proc.returncode == 0 and tmp_out.is_file():
                    upscaled_rgb = _imread_rgb(tmp_out)
                    if (upscaled_rgb.shape[1], upscaled_rgb.shape[0]) != (nw, nh):
                        upscaled_rgb = cv2.resize(upscaled_rgb, (nw, nh), interpolation=cv2.INTER_LANCZOS4)
                tmp_out.unlink(missing_ok=True)
            except Exception:
                pass

    if upscaled_rgb is None:
        pil_im = Image.fromarray(orig_rgb, mode="RGB").resize((nw, nh), Image.Resampling.LANCZOS)
        pil_im = pil_im.filter(ImageFilter.UnsharpMask(radius=1.6, percent=135, threshold=2))
        upscaled_rgb = np.array(pil_im, dtype=np.uint8)

    next_ver = len(item.get("history") or []) + 1
    hist_rel = f"history/{item_id}_v{next_ver}_upscale{factor}x.png"
    _imwrite_png(p / hist_rel, upscaled_rgb)
    _imwrite_png(raw_abs, upscaled_rgb)

    item["width"] = nw
    item["height"] = nh
    item.setdefault("history", []).append({
        "ver": next_ver,
        "kind": f"upscale_{factor}x",
        "file": hist_rel,
        "width": nw,
        "height": nh,
        "at": _now_sec(),
        "note": f"{factor}x 超清放大 ({nw}x{nh})",
    })
    _post_process_item(p, item)
    save_project(p, data)
    return {
        "ok": True,
        "item_id": item_id,
        "scale": factor,
        "width": nw,
        "height": nh,
        "version": next_ver,
        "item": item,
    }


def revert_item(
    proj_dir: str | Path,
    item_id: str,
    version: int = 1,
) -> dict[str, Any]:
    """将指定图片恢复到 `history` 中的某个历史版本，并重新执行人脸体检与非破坏性文字排版。"""
    p = ensure_project_dirs(proj_dir)
    data = load_project(p)
    item = _find_item(data, item_id)
    hist = item.get("history") or []
    if not hist:
        return {"ok": False, "error": "该图片尚无历史版本记录"}

    target_entry = None
    for h_ent in hist:
        if int(h_ent.get("ver") or 0) == int(version):
            target_entry = h_ent
            break
    if target_entry is None:
        target_entry = hist[0]

    snap_abs = p / target_entry["file"]
    if not snap_abs.is_file():
        return {"ok": False, "error": f"历史版本文件不存在: {snap_abs}"}

    raw_abs = p / item["raw_file"]
    shutil.copy2(snap_abs, raw_abs)
    with Image.open(raw_abs) as im:
        item["width"], item["height"] = im.size
    item["aspect"] = _guess_aspect_label(item["width"], item["height"])

    next_ver = len(hist) + 1
    hist.append({
        "ver": next_ver,
        "kind": "revert",
        "file": target_entry["file"],
        "reverted_to": target_entry.get("ver", 1),
        "at": _now_sec(),
        "note": f"回退至版本 v{target_entry.get('ver', 1)}",
    })
    _post_process_item(p, item)
    save_project(p, data)
    return {
        "ok": True,
        "item_id": item_id,
        "reverted_to": target_entry.get("ver", 1),
        "version": next_ver,
        "item": item,
    }


