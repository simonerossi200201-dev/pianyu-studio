def _imread_rgb(path: Path) -> np.ndarray:
    """Unicode-safe RGB image reader."""
    with Image.open(path) as im:
        return np.array(im.convert("RGB"), dtype=np.uint8)


def _imread_rgba(path: Path) -> np.ndarray:
    """Unicode-safe RGBA image reader."""
    with Image.open(path) as im:
        return np.array(im.convert("RGBA"), dtype=np.uint8)


def _imwrite_png(path: Path, arr: np.ndarray) -> None:
    """Unicode-safe PNG image writer."""
    path.parent.mkdir(parents=True, exist_ok=True)
    mode = "RGBA" if (arr.ndim == 3 and arr.shape[2] == 4) else ("L" if arr.ndim == 2 else "RGB")
    Image.fromarray(arr, mode=mode).save(path, format="PNG")


