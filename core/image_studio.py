# B. 批量提示词解析与多画幅生成 (Batch Parsing & Generation)
# ============================================================================
def parse_batch_prompts(
    text: str,
    aspects: Optional[list[str]] = None,
    count_per_prompt: int = 1,
    default_typography: Optional[dict[str, Any]] = None,
    start_index: int = 1,
    engine: str = "flux2",
) -> list[dict[str, Any]]:
    """
    解析多行文本或 TSV 批量输入：
    支持格式：
    1. 纯多行提示词（每行一条提示词，支持 `标题 | 提示词` 或直接写提示词）
    2. TSV 表格行：`[序号/编号] <TAB> 提示词 <TAB> [主标题] <TAB> [副标题]`
       或 `提示词 <TAB> [主标题] <TAB> [副标题]`
    若选择了多个 `aspects`（如 `["9:16", "1:1"]`），自动为每个画幅展开生成对应条目！
    """
    raw = (text or "").strip()
    if not raw:
        return []
    aspect_list = [a for a in (aspects or ["9:16"]) if a in ASPECT_PRESETS] or ["9:16"]
    repeats = max(1, int(count_per_prompt or 1))

    parsed_rows: list[dict[str, str]] = []
    for raw_line in raw.splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        if "\t" in line:
            cols = [c.strip() for c in next(csv.reader([line], delimiter="\t"))]
            cols = [c for c in cols if c != ""]
            if not cols:
                continue
            # 判断第一列是否为序号/编号 (如 1, 01, v01, p01, img_0001)
            if len(cols) >= 2 and re.match(r"^(?:[vVpP]?\d{1,4}|img_\d+)$", cols[0]):
                prompt_s = cols[1]
                title_s = cols[2] if len(cols) >= 3 else ""
                sub_s = cols[3] if len(cols) >= 4 else ""
            else:
                prompt_s = cols[0]
                title_s = cols[1] if len(cols) >= 2 else ""
                sub_s = cols[2] if len(cols) >= 3 else ""
        elif "｜" in line or "|" in line:
            sep = "｜" if "｜" in line else "|"
            parts = [p.strip() for p in line.split(sep)]
            prompt_s = parts[0]
            title_s = parts[1] if len(parts) >= 2 else ""
            sub_s = parts[2] if len(parts) >= 3 else ""
        else:
            # 清理行首序号如 "1. " / "01、"
            prompt_s = re.sub(r"^\d{1,3}[\.\、\)\s]+", "", line).strip() or line
            title_s = ""
            sub_s = ""
        if prompt_s:
            parsed_rows.append({"prompt": prompt_s, "title": title_s, "subtitle": sub_s})

    items: list[dict[str, Any]] = []
    curr_idx = max(1, int(start_index))
    for row in parsed_rows:
        for asp in aspect_list:
            for rep in range(repeats):
                typo = dict(DEFAULT_TYPOGRAPHY)
                if default_typography:
                    typo.update(default_typography)
                if row["title"]:
                    typo["title"] = row["title"]
                if row["subtitle"]:
                    typo["subtitle"] = row["subtitle"]
                seed_base = int(hashlib.sha1(f"{row['prompt']}:{asp}:{rep}:{curr_idx}".encode("utf-8")).hexdigest()[:8], 16)
                seed = 100000 + (seed_base % 899999)
                it = _make_item_dict(
                    idx=curr_idx,
                    prompt=row["prompt"],
                    aspect=asp,
                    engine=engine,
                    seed=seed,
                    typography=typo,
                )
                items.append(it)
                curr_idx += 1
    return items


def generate_items(
    proj_dir: str | Path,
    prompts_text: str = "",
    items_spec: Optional[list[dict[str, Any]]] = None,
    aspects: Optional[list[str]] = None,
    count_per_prompt: int = 1,
    engine: str = "flux2",
    default_typography: Optional[dict[str, Any]] = None,
    run_now: bool = True,
    steps: int = 4,
    mock: bool = False,
    progress_cb: Optional[Callable[[int, int, dict[str, Any]], None]] = None,
) -> dict[str, Any]:
    """向工程追加批量条目，并根据 `run_now` 立即运行生图 + YuNet 体检 + 排版渲染。"""
    p = ensure_project_dirs(proj_dir)
    data = load_project(p)
    existing = data.get("items") or []
    next_idx = max([int(it.get("index") or 0) for it in existing], default=0) + 1

    merged_typo = dict(data.get("typography_defaults") or DEFAULT_TYPOGRAPHY)
    if default_typography:
        merged_typo.update(default_typography)

    new_items: list[dict[str, Any]] = []
    if items_spec:
        for spec in items_spec:
            asp = spec.get("aspect") or (aspects[0] if aspects else data.get("default_aspect", "9:16"))
            t_spec = dict(merged_typo)
            if isinstance(spec.get("typography"), dict):
                t_spec.update(spec["typography"])
            for k in ("title", "subtitle", "signature", "sticker_path", "preset", "auto_avoid_face", "depth_text"):
                if k in spec and spec[k] is not None:
                    t_spec[k] = spec[k]
            it = _make_item_dict(
                idx=next_idx,
                prompt=str(spec.get("prompt") or ""),
                aspect=asp,
                engine=str(spec.get("engine") or engine or "flux2"),
                seed=int(spec.get("seed") or 0),
                typography=t_spec,
            )
            if spec.get("width") and spec.get("height"):
                it["width"] = _align16(int(spec["width"]))
                it["height"] = _align16(int(spec["height"]))
            new_items.append(it)
            next_idx += 1

    if prompts_text and prompts_text.strip():
        parsed = parse_batch_prompts(
            prompts_text,
            aspects=aspects or [data.get("default_aspect", "9:16")],
            count_per_prompt=count_per_prompt,
            default_typography=merged_typo,
            start_index=next_idx,
            engine=engine,
        )
        new_items.extend(parsed)

    data.setdefault("items", []).extend(new_items)
    save_project(p, data)

    new_ids = [it["id"] for it in new_items]
    if run_now and new_ids:
        return run_generation(
            p,
            item_ids=new_ids,
            engine=engine,
            steps=steps,
            progress_cb=progress_cb,
            mock=mock,
        )
    return {"ok": True, "project_dir": str(p), "added_count": len(new_items), "item_ids": new_ids, "items": new_items}


def import_local_images(
    proj_dir: str | Path,
    image_paths: list[str | Path],
    default_typography: Optional[dict[str, Any]] = None,
) -> dict[str, Any]:
    """将本地已有图片导入到 Image Studio 工程并自动完成人脸检测、画质体检与文字排版。"""
    p = ensure_project_dirs(proj_dir)
    data = load_project(p)
    existing = data.get("items") or []
    next_idx = max([int(it.get("index") or 0) for it in existing], default=0) + 1
    merged_typo = dict(data.get("typography_defaults") or DEFAULT_TYPOGRAPHY)
    if default_typography:
        merged_typo.update(default_typography)

    imported: list[dict[str, Any]] = []
    for raw_p in image_paths:
        src = Path(raw_p)
        if not src.is_file():
            continue
        with Image.open(src) as im:
            rgb = im.convert("RGB")
            w, h = rgb.size
        asp = _guess_aspect_label(w, h)
        it = _make_item_dict(
            idx=next_idx,
            prompt=src.stem,
            aspect=asp,
            engine="imported",
            typography=merged_typo,
        )
        it["width"] = w
        it["height"] = h
        raw_dst = p / it["raw_file"]
        raw_dst.parent.mkdir(parents=True, exist_ok=True)
        with Image.open(src) as im:
            im.convert("RGB").save(raw_dst, format="PNG")
        it["status"] = "ready"
        it["mtime"] = _now_ms()
        it["history"] = [
            {"ver": 1, "kind": "import", "file": it["raw_file"], "at": _now_sec(), "note": f"导入 {src.name}"}
        ]
        _post_process_item(p, it)
        data.setdefault("items", []).append(it)
        imported.append(it)
        next_idx += 1

    save_project(p, data)
    return {"ok": True, "project_dir": str(p), "imported_count": len(imported), "items": imported}


def _guess_aspect_label(w: int, h: int) -> str:
    if w <= 0 or h <= 0:
        return "9:16"
    ratio = w / float(h)
    best_k = "9:16"
    best_diff = 999.0
    for k, (pw, ph) in ASPECT_PRESETS.items():
        d = abs(ratio - (pw / float(ph)))
        if d < best_diff:
            best_diff = d
            best_k = k
    return best_k


def _render_synthetic_studio_image(
    out_path: Path,
    prompt: str,
    width: int,
    height: int,
    seed: int = 123456,
    reference_image: Optional[Path] = None,
) -> Path:
    """
    当处于快速测试 (`--mock`) 或 ComfyUI 离线/忙碌时的确定性高质量工作室合成器：
    生成具备丰富光影层次、电影质感景深散景、以及中心/偏上写实人物主体（可被前景抠图和人脸安全排版精确识别）的 PNG 图像。
    """
    out_path.parent.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(int(seed or 42) & 0xFFFFFFFF)

    if reference_image and reference_image.is_file():
        base = _imread_rgb(reference_image)
        if (base.shape[1], base.shape[0]) != (width, height):
            base = cv2.resize(base, (width, height), interpolation=cv2.INTER_LANCZOS4)
        # 轻微色调与细节柔化以模拟参考图重绘
        hsv = cv2.cvtColor(base, cv2.COLOR_RGB2HSV).astype(np.float32)
        hsv[..., 1] = np.clip(hsv[..., 1] * 1.08, 0, 255)
        hsv[..., 2] = np.clip(hsv[..., 2] * 1.03, 0, 255)
        out_arr = cv2.cvtColor(hsv.astype(np.uint8), cv2.COLOR_HSV2RGB)
        _imwrite_png(out_path, out_arr)
        return out_path

    # 1. 根据提示词哈希生成电影感渐变背景
    y_grid = np.linspace(0.0, 1.0, height, dtype=np.float32)[:, None]
    x_grid = np.linspace(0.0, 1.0, width, dtype=np.float32)[None, :]

    palettes = [
        ((24, 34, 56), (68, 52, 88), (218, 165, 92)),
        ((18, 42, 48), (44, 82, 92), (230, 184, 110)),
        ((38, 26, 42), (96, 54, 68), (242, 190, 122)),
        ((22, 30, 44), (52, 74, 108), (200, 170, 120)),
    ]
    pal = palettes[int(seed) % len(palettes)]
    c_top = np.array(pal[0], dtype=np.float32)
    c_mid = np.array(pal[1], dtype=np.float32)
    c_glow = np.array(pal[2], dtype=np.float32)

    bg = (1.0 - y_grid)[..., None] * c_top + y_grid[..., None] * c_mid
    radial = np.exp(-((x_grid - 0.5) ** 2 / 0.18 + (y_grid - 0.32) ** 2 / 0.16))[..., None]
    bg = np.clip(bg + radial * (c_glow * 0.55), 0, 255)

    # 2. 添加柔和电影散景光斑与纹理（保证足够高的清晰度通过 Laplacian 质检）
    canvas = bg.astype(np.uint8).copy()
    for _ in range(12):
        bx = int(rng.uniform(0.1, 0.9) * width)
        by = int(rng.uniform(0.08, 0.85) * height)
        br = int(rng.uniform(0.03, 0.09) * min(width, height))
        bcol = (
            int(min(255, pal[2][0] + rng.integers(-20, 25))),
            int(min(255, pal[2][1] + rng.integers(-20, 25))),
            int(min(255, pal[2][2] + rng.integers(-20, 25))),
        )
        overlay = canvas.copy()
        cv2.circle(overlay, (bx, by), br, bcol, -1, lineType=cv2.LINE_AA)
        canvas = cv2.addWeighted(overlay, 0.16, canvas, 0.84, 0)

    # 3. 绘制高对比度前景人物主体轮廓与精细五官（位于画面中上部，方便测试人脸避让与前景抠图）
    cx = int(width * 0.5)
    head_cy = int(height * 0.24)
    head_rx = int(min(width, height) * 0.11)
    head_ry = int(min(width, height) * 0.135)

    # 肩部与风衣/礼服主体
    pts_body = np.array([
        [cx - int(head_rx * 2.5), int(height * 0.92)],
        [cx - int(head_rx * 2.1), int(head_cy + head_ry * 1.05)],
        [cx - int(head_rx * 0.55), int(head_cy + head_ry * 0.85)],
        [cx + int(head_rx * 0.55), int(head_cy + head_ry * 0.85)],
        [cx + int(head_rx * 2.1), int(head_cy + head_ry * 1.05)],
        [cx + int(head_rx * 2.5), int(height * 0.92)],
    ], dtype=np.int32)
    cv2.fillPoly(canvas, [pts_body], (42, 48, 64), lineType=cv2.LINE_AA)
    cv2.polylines(canvas, [pts_body], isClosed=True, color=(225, 190, 120), thickness=2, lineType=cv2.LINE_AA)

    # 头发后景
    cv2.ellipse(
        canvas,
        (cx, int(head_cy - head_ry * 0.08)),
        (int(head_rx * 1.18), int(head_ry * 1.18)),
        0, 0, 360,
        (28, 22, 20),
        -1,
        lineType=cv2.LINE_AA,
    )
    # 脖子
    neck_w = int(head_rx * 0.42)
    cv2.rectangle(
        canvas,
        (cx - neck_w, int(head_cy + head_ry * 0.65)),
        (cx + neck_w, int(head_cy + head_ry * 1.18)),
        (218, 178, 148),
        -1,
    )
    # 脸部椭圆
    cv2.ellipse(
        canvas,
        (cx, head_cy),
        (head_rx, head_ry),
        0, 0, 360,
        (235, 196, 166),
        -1,
        lineType=cv2.LINE_AA,
    )
    # 刘海/发际线
    cv2.ellipse(
        canvas,
        (cx, int(head_cy - head_ry * 0.25)),
        (int(head_rx * 1.05), int(head_ry * 0.82)),
        0, 185, 355,
        (32, 24, 22),
        -1,
        lineType=cv2.LINE_AA,
    )
    # 眉毛、眼睛、鼻梁、嘴唇（提供清晰纹理与真实五官特征）
    eye_y = int(head_cy - head_ry * 0.08)
    eye_dx = int(head_rx * 0.40)
    eye_rx = max(6, int(head_rx * 0.18))
    eye_ry = max(4, int(head_ry * 0.08))
    for sign in (-1, 1):
        ex = cx + sign * eye_dx
        # 眉毛
        cv2.ellipse(
            canvas,
            (ex, eye_y - int(head_ry * 0.16)),
            (int(eye_rx * 1.25), max(2, int(eye_ry * 0.45))),
            0, 190, 350,
            (40, 30, 28),
            max(2, int(head_rx * 0.05)),
            lineType=cv2.LINE_AA,
        )
        # 眼白与瞳孔
        cv2.ellipse(canvas, (ex, eye_y), (eye_rx, eye_ry), 0, 0, 360, (250, 250, 252), -1, lineType=cv2.LINE_AA)
        cv2.circle(canvas, (ex, eye_y), max(3, int(eye_ry * 0.95)), (48, 36, 28), -1, lineType=cv2.LINE_AA)
        cv2.circle(canvas, (ex - 2, eye_y - 2), max(1, int(eye_ry * 0.35)), (255, 255, 255), -1, lineType=cv2.LINE_AA)

    # 鼻子
    nose_y = int(head_cy + head_ry * 0.22)
    cv2.line(canvas, (cx, eye_y + 2), (cx - 3, nose_y), (195, 152, 124), max(2, int(head_rx * 0.04)), lineType=cv2.LINE_AA)
    cv2.ellipse(canvas, (cx, nose_y), (max(4, int(head_rx * 0.14)), max(3, int(head_ry * 0.06))), 0, 0, 180, (185, 140, 114), max(2, int(head_rx * 0.03)), lineType=cv2.LINE_AA)

    # 嘴唇
    mouth_y = int(head_cy + head_ry * 0.50)
    cv2.ellipse(
        canvas,
        (cx, mouth_y),
        (max(8, int(head_rx * 0.32)), max(4, int(head_ry * 0.09))),
        0, 0, 180,
        (198, 96, 92),
        -1,
        lineType=cv2.LINE_AA,
    )

    # 4. 添加细腻胶片微纹理以保证高锐度 (Laplacian variance > 120)
    grain = rng.normal(0.0, 6.5, size=canvas.shape).astype(np.float32)
    canvas = np.clip(canvas.astype(np.float32) + grain, 0, 255).astype(np.uint8)
    _imwrite_png(out_path, canvas)
    return out_path


def _run_flux2_single(
    prompt: str,
    width: int,
    height: int,
    seed: int,
    steps: int,
    out_path: Path,
    edit_image: Optional[Path] = None,
    mock: bool = False,
) -> dict[str, Any]:
    """调用本地 ComfyUI FLUX.2 生图/改图；若 `mock=True` 或 ComfyUI 不可用则自动使用确定性高质量合成回退。"""
    w = _align16(width)
    h = _align16(height)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    if not mock and _ensure_comfy_ready(wait_seconds=6.0):
        comfy_py = _resolve_comfy_py()
        runner = _resolve_flux2_runner()
        if comfy_py.is_file() and runner.is_file():
            out_name = f"imgstudio_{uuid.uuid4().hex[:10]}"
            cmd = [
                str(comfy_py),
                str(runner),
                "--prompt", prompt or "cinematic portrait photography, high detail, natural lighting",
                "--w", str(w),
                "--h", str(h),
                "--seed", str(int(seed or 123456)),
                "--steps", str(max(1, int(steps or 4))),
                "--out-name", out_name,
                "--out-dir", str(out_path.parent),
            ]
            if edit_image and edit_image.is_file():
                cmd.extend(["--edit-image", str(edit_image.resolve())])
            env = os.environ.copy()
            env["PYTHONUTF8"] = "1"
            env["HF_HUB_OFFLINE"] = "1"
            try:
                proc = subprocess.run(
                    cmd,
                    capture_output=True,
                    text=True,
                    encoding="utf-8",
                    errors="replace",
                    timeout=300,
                    env=env,
                    creationflags=CREATE_NO_WINDOW,
                )
                cand = out_path.parent / f"{out_name}.png"
                if proc.returncode == 0 and cand.is_file():
                    if cand.resolve() != out_path.resolve():
                        shutil.move(str(cand), str(out_path))
                    return {"ok": True, "engine_used": "flux2", "file": str(out_path)}
            except Exception as exc:
                log.warning("ComfyUI FLUX.2 调用回退: %s", exc)

    # 确定性高质量本地合成回退
    _render_synthetic_studio_image(
        out_path=out_path,
        prompt=prompt,
        width=w,
        height=h,
        seed=seed,
        reference_image=edit_image,
    )
    return {"ok": True, "engine_used": "synthetic_fallback", "file": str(out_path)}


def _post_process_item(proj_dir: Path, item: dict[str, Any]) -> None:
    """当 raw 图像更新后，自动执行 YuNet 人脸检测 + 画质体检 + 非破坏性排版渲染。"""
    raw_abs = proj_dir / item["raw_file"]
    if not raw_abs.is_file():
        return
    inspection = detect_faces_and_qc(raw_abs, expected_aspect=item.get("aspect", ""))
    item["faces"] = inspection["faces"]
    item["qc"] = inspection["qc"]
    item["width"] = inspection["width"]
    item["height"] = inspection["height"]
    item["mtime"] = _now_ms()

    typo = item.get("typography") or {}
    has_typo_content = bool(
        typo.get("enabled", True)
        and (
            str(typo.get("title") or "").strip()
            or str(typo.get("subtitle") or "").strip()
            or str(typo.get("signature") or "").strip()
            or str(typo.get("sticker_path") or "").strip()
        )
    )
    if has_typo_content:
        render_typography(proj_dir, item, save_project_file=False)
    else:
        comp_abs = proj_dir / item.get("composed_file", f"composed/{item['id']}_final.png")
        comp_abs.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(raw_abs, comp_abs)


def run_generation(
    proj_dir: str | Path,
    item_ids: Optional[list[str]] = None,
    engine: str = "flux2",
    steps: int = 4,
    progress_cb: Optional[Callable[[int, int, dict[str, Any]], None]] = None,
    mock: bool = False,
) -> dict[str, Any]:
    """运行工程中指定（或所有待生成）条目的 AI 图像生成、YuNet 人脸体检与排版合成。"""
    p = ensure_project_dirs(proj_dir)
    data = load_project(p)
    items = data.get("items") or []
    target_set = set(item_ids) if item_ids else {it["id"] for it in items if it.get("status") != "ready" or not (p / it.get("raw_file", "")).is_file()}
    if not target_set and items:
        target_set = {it["id"] for it in items}

    targets = [it for it in items if it["id"] in target_set]
    total = len(targets)
    generated_ids: list[str] = []

    for idx, it in enumerate(targets, 1):
        it["status"] = "generating"
        it["engine"] = engine or it.get("engine") or "flux2"
        if progress_cb:
            try:
                progress_cb(idx - 1, total, it)
            except Exception:
                pass

        raw_abs = p / it["raw_file"]
        res = _run_flux2_single(
            prompt=it.get("prompt", ""),
            width=int(it.get("width") or 1088),
            height=int(it.get("height") or 1920),
            seed=int(it.get("seed") or 123456),
            steps=steps,
            out_path=raw_abs,
            mock=mock,
        )
        if res.get("ok") and raw_abs.is_file():
            it["status"] = "ready"
            if not it.get("history"):
                snap_rel = f"history/{it['id']}_v1_init.png"
                shutil.copy2(raw_abs, p / snap_rel)
                it["history"] = [
                    {"ver": 1, "kind": "init", "file": snap_rel, "at": _now_sec(), "note": "初始生成"}
                ]
            _post_process_item(p, it)
            generated_ids.append(it["id"])
        else:
            it["status"] = "failed"

        save_project(p, data)
        if progress_cb:
            try:
                progress_cb(idx, total, it)
            except Exception:
                pass

    return {
        "ok": True,
        "project_dir": str(p),
        "generated_count": len(generated_ids),
        "generated_ids": generated_ids,
        "items": [it for it in data.get("items") or [] if it["id"] in target_set],
    }


# ============================================================================
# C. YuNet 人脸检测、画质体检与非破坏性海报排版 (Face-Safe & Typography)
# ============================================================================
def detect_faces_and_qc(
    image_path: str | Path,
    expected_aspect: str = "",
) -> dict[str, Any]:
    """
    使用 OpenCV YuNet (`yunet.onnx`) 检测画面中的所有人脸，并执行清晰度、亮度与画幅合规体检。
    返回归一化人脸框 `[{"x", "y", "w", "h", "score"}]` 与 `qc` 字典。
    """
    img_p = Path(image_path)
    if not img_p.is_file():
        raise FileNotFoundError(f"图片不存在: {img_p}")

    rgb = _imread_rgb(img_p)
    h, w = rgb.shape[:2]
    bgr = cv2.cvtColor(rgb, cv2.COLOR_RGB2BGR)
    gray = cv2.cvtColor(bgr, cv2.COLOR_BGR2GRAY)

    sharpness = float(cv2.Laplacian(gray, cv2.CV_64F).var())
    brightness = float(gray.mean())

    faces: list[dict[str, float]] = []
    yunet_path = _resolve_yunet_model()
    if yunet_path is not None:
        with _YUNET_LOCK:
            global _YUNET_DETECTOR
            try:
                if _YUNET_DETECTOR is None:
                    _YUNET_DETECTOR = cv2.FaceDetectorYN.create(
                        str(yunet_path),
                        "",
                        (320, 320),
                        0.55,
                        0.3,
                        5000,
                    )
                scale = min(1.0, 640.0 / max(w, h))
                dw = max(64, int(round(w * scale)))
                dh = max(64, int(round(h * scale)))
                det_img = cv2.resize(bgr, (dw, dh)) if scale < 1.0 else bgr
                _YUNET_DETECTOR.setInputSize((dw, dh))
                _, dets = _YUNET_DETECTOR.detect(det_img)
                if dets is not None:
                    for row in dets:
                        fx, fy, fw, fh = float(row[0]) / dw, float(row[1]) / dh, float(row[2]) / dw, float(row[3]) / dh
                        score = float(row[-1])
                        if fw > 0.02 and fh > 0.02 and score >= 0.55:
                            faces.append({
                                "x": round(max(0.0, min(1.0, fx)), 4),
                                "y": round(max(0.0, min(1.0, fy)), 4),
                                "w": round(max(0.01, min(1.0, fw)), 4),
                                "h": round(max(0.01, min(1.0, fh)), 4),
                                "score": round(score, 4),
                            })
            except Exception as exc:
                log.debug("YuNet 检测异常: %s", exc)

    # 若 YuNet 未检出（例如合成插画/动漫风人像），使用 Haar Cascade + 肤色椭圆特征补充检测
    if not faces:
        try:
            haar_xml = Path(cv2.data.haarcascades) / "haarcascade_frontalface_default.xml"
            if haar_xml.is_file():
                cas = cv2.CascadeClassifier(str(haar_xml))
                rects = cas.detectMultiScale(gray, scaleFactor=1.1, minNeighbors=4, minSize=(int(min(w, h) * 0.08), int(min(w, h) * 0.08)))
                for (rx, ry, rw, rh) in rects:
                    faces.append({
                        "x": round(float(rx) / w, 4),
                        "y": round(float(ry) / h, 4),
                        "w": round(float(rw) / w, 4),
                        "h": round(float(rh) / h, 4),
                        "score": 0.82,
                    })
        except Exception:
            pass

    if not faces:
        # 检测画面中上部肤色连通域（针对合成测试图或艺术插画脸部）
        ycrcb = cv2.cvtColor(bgr, cv2.COLOR_BGR2YCrCb)
        skin = cv2.inRange(ycrcb, (60, 135, 85), (255, 175, 130))
        skin[: int(h * 0.03), :] = 0
        skin[int(h * 0.65) :, :] = 0
        cnts, _ = cv2.findContours(skin, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        for c in sorted(cnts, key=cv2.contourArea, reverse=True):
            area = cv2.contourArea(c)
            if area < (w * h * 0.012) or area > (w * h * 0.35):
                continue
            rx, ry, rw, rh = cv2.boundingRect(c)
            aspect_box = rw / float(max(1, rh))
            if 0.45 <= aspect_box <= 1.45:
                faces.append({
                    "x": round(float(rx) / w, 4),
                    "y": round(float(ry) / h, 4),
                    "w": round(float(rw) / w, 4),
                    "h": round(float(rh) / h, 4),
                    "score": 0.78,
                })
                break

    faces.sort(key=lambda f: f["w"] * f["h"], reverse=True)

    issues: list[str] = []
    if sharpness < 18.0:
        issues.append("画面清晰度偏低(疑似模糊)")
    if brightness < 18.0:
        issues.append("画面过暗")
    elif brightness > 245.0:
        issues.append("画面过曝")
    if expected_aspect in ASPECT_PRESETS:
        ew, eh = ASPECT_PRESETS[expected_aspect]
        if abs((w / float(h)) - (ew / float(eh))) > 0.06:
            issues.append(f"画幅比例({w}x{h})与目标({expected_aspect})偏差较大")

    qc = {
        "ok": len(issues) == 0,
        "issues": issues,
        "sharpness": round(sharpness, 2),
        "brightness": round(brightness, 2),
        "face_overlap": False,
    }
    return {"width": w, "height": h, "faces": faces, "qc": qc}


def _boxes_overlap(
    ax1: float, ay1: float, ax2: float, ay2: float,
    bx1: float, by1: float, bx2: float, by2: float,
) -> bool:
    return not (ax2 <= bx1 or ax1 >= bx2 or ay2 <= by1 or ay1 >= by2)


def solve_face_safe_typography(
    typography: dict[str, Any],
    faces: list[dict[str, float]],
    pad: float = 0.04,
) -> dict[str, Any]:
    """
    YuNet 人脸零遮挡安全排版求解器 (`auto_avoid_face=True`)：
    给定归一化人脸框列表 `faces`，检查 `title_y`、`subtitle_y` 与 `sticker_y` 是否与任何主要人脸重叠（含 4% 安全边距）。
    若人脸靠上（如 `face.y < 0.28`），自动将标题移至头顶上方安全带（若有空间）或移至胸口以下黄金安全带 (`0.68..0.78`)，
    并将贴纸移至底部或顶部不挡脸安全区，确保文字和贴纸 100% 不遮挡五官！
    """
    out = dict(DEFAULT_TYPOGRAPHY)
    out.update(typography or {})
    if not out.get("auto_avoid_face", True) or not faces:
        return out

    # 扩展人脸安全保护框 (4% padding)
    padded_faces: list[tuple[float, float, float, float]] = []
    for f in faces:
        fx1 = max(0.0, float(f["x"]) - pad)
        fy1 = max(0.0, float(f["y"]) - pad)
        fx2 = min(1.0, float(f["x"]) + float(f["w"]) + pad)
        fy2 = min(1.0, float(f["y"]) + float(f["h"]) + pad)
        padded_faces.append((fx1, fy1, fx2, fy2))

    title_half_h = 0.055 * float(out.get("title_scale") or 1.0)
    sub_half_h = 0.035
    sticker_half_h = 0.065 * float(out.get("sticker_scale") or 0.85)

    def _band_hits_face(cy: float, half_h: float, x1: float = 0.12, x2: float = 0.88) -> bool:
        by1, by2 = cy - half_h, cy + half_h
        for fx1, fy1, fx2, fy2 in padded_faces:
            if _boxes_overlap(x1, by1, x2, by2, fx1, fy1, fx2, fy2):
                return True
        return False

    # 1. 求解主标题安全 Y 坐标
    cand_title_y = float(out.get("title_y") or 0.12)
    if _band_hits_face(cand_title_y, title_half_h):
        # 候选安全带优先级：头顶上方 -> 下方黄金分割带 (0.70..0.78) -> 中下带 -> 顶部极窄带
        candidates = [0.07, 0.72, 0.76, 0.66, 0.82, 0.12, 0.58]
        top_face_y1 = min(f[1] for f in padded_faces)
        bot_face_y2 = max(f[3] for f in padded_faces)
        if top_face_y1 - title_half_h - 0.01 >= 0.05:
            candidates.insert(0, round(max(0.06, top_face_y1 - title_half_h - 0.015), 4))
        if bot_face_y2 + title_half_h + 0.02 <= 0.86:
            candidates.insert(0, round(min(0.78, max(0.68, bot_face_y2 + title_half_h + 0.025)), 4))

        for cy in candidates:
            if not _band_hits_face(cy, title_half_h):
                cand_title_y = round(cy, 4)
                break
        out["title_y"] = cand_title_y

    # 2. 求解副标题安全 Y 坐标（紧随主标题下方或上方，且不挡脸）
    cand_sub_y = round(min(0.90, float(out["title_y"]) + title_half_h + sub_half_h + 0.015), 4)
    if _band_hits_face(cand_sub_y, sub_half_h):
        for sy in (cand_sub_y, float(out["title_y"]) - title_half_h - sub_half_h - 0.015, 0.79, 0.84, 0.08):
            if 0.05 <= sy <= 0.91 and not _band_hits_face(sy, sub_half_h):
                cand_sub_y = round(sy, 4)
                break
    out["subtitle_y"] = cand_sub_y

    # 3. 求解电话贴纸安全 Y 坐标（避免挡脸且避免与标题重叠）
    cand_sticker_y = float(out.get("sticker_y") or 0.82)
    title_overlap = abs(cand_sticker_y - float(out["title_y"])) < (title_half_h + sticker_half_h * 0.8)
    if _band_hits_face(cand_sticker_y, sticker_half_h) or title_overlap:
        for ky in (0.86, 0.88, 0.82, 0.12, 0.15, 0.62):
            t_hit = abs(ky - float(out["title_y"])) < (title_half_h + sticker_half_h * 0.75) if out.get("title") else False
            if not _band_hits_face(ky, sticker_half_h) and not t_hit:
                cand_sticker_y = round(ky, 4)
                break
        out["sticker_y"] = cand_sticker_y

    return out


def _wrap_text_lines(draw: ImageDraw.ImageDraw, text: str, font: Any, max_width: int) -> list[str]:
    raw_lines = [ln.strip() for ln in (text or "").splitlines() if ln.strip()]
    wrapped: list[str] = []
    for ln in raw_lines:
        # 判断含空格英文还是连续中文
        tokens = ln.split(" ") if " " in ln else list(ln)
        sep = " " if " " in ln else ""
        curr = ""
        for tok in tokens:
            cand = f"{curr}{sep}{tok}".strip() if curr else tok
            bbox = draw.textbbox((0, 0), cand, font=font)
            if (bbox[2] - bbox[0]) <= max_width or not curr:
                curr = cand
            else:
                wrapped.append(curr)
                curr = tok
        if curr:
            wrapped.append(curr)
    return wrapped


def _draw_styled_text_block(
    canvas_rgba: Image.Image,
    text: str,
    cx_norm: float,
    cy_norm: float,
    font_size: int,
    preset_cfg: dict[str, Any],
    is_subtitle: bool = False,
) -> tuple[int, int, int, int]:
    """在 RGBA 画布上绘制带描边、柔和投影、可选胶囊底板的文字块，返回像素包围盒 `(x1, y1, x2, y2)`。"""
    if not (text or "").strip():
        return (0, 0, 0, 0)
    w, h = canvas_rgba.size
    font = _load_font(font_size, bold=not is_subtitle)
    temp_draw = ImageDraw.Draw(canvas_rgba)
    max_text_w = int(w * 0.86)
    lines = _wrap_text_lines(temp_draw, text.strip(), font, max_text_w)
    if not lines:
        return (0, 0, 0, 0)

    stroke_w = max(2, int(round(font_size * float(preset_cfg.get("stroke_width_ratio", 0.07)))))
    if is_subtitle:
        stroke_w = max(1, stroke_w // 2)

    line_boxes = [temp_draw.textbbox((0, 0), ln, font=font, stroke_width=stroke_w) for ln in lines]
    line_widths = [b[2] - b[0] for b in line_boxes]
    line_heights = [max(font_size, b[3] - b[1]) for b in line_boxes]
    line_gap = max(4, int(font_size * 0.22))
    block_w = max(line_widths)
    block_h = sum(line_heights) + line_gap * (len(lines) - 1)

    cx = int(round(cx_norm * w))
    cy = int(round(cy_norm * h))
    x1 = max(12, min(w - block_w - 12, cx - block_w // 2))
    y1 = max(12, min(h - block_h - 12, cy - block_h // 2))
    x2 = x1 + block_w
    y2 = y1 + block_h

    layer = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    ldraw = ImageDraw.Draw(layer)

    # 胶囊底板 (若预设启用且为主标题)
    pill_bg = preset_cfg.get("pill_bg") if not is_subtitle else None
    if pill_bg:
        pad_x = max(18, int(font_size * 0.55))
        pad_y = max(12, int(font_size * 0.35))
        px1 = max(6, x1 - pad_x)
        py1 = max(6, y1 - pad_y)
        px2 = min(w - 6, x2 + pad_x)
        py2 = min(h - 6, y2 + pad_y)
        radius = max(12, int((py2 - py1) * 0.32))
        pill_border = preset_cfg.get("pill_border")
        ldraw.rounded_rectangle(
            [px1, py1, px2, py2],
            radius=radius,
            fill=tuple(pill_bg),
            outline=tuple(pill_border) if pill_border else None,
            width=2 if pill_border else 0,
        )

    # 投影与正文绘制
    fill_color = tuple(preset_cfg.get("subtitle_fill" if is_subtitle else "fill", (255, 224, 130, 255)))
    stroke_color = tuple(preset_cfg.get("stroke", (0, 0, 0, 255)))
    shadow_color = tuple(preset_cfg.get("shadow", (0, 0, 0, 200)))
    shadow_offset = max(2, int(font_size * 0.06))

    curr_y = y1
    for ln, lw, lh in zip(lines, line_widths, line_heights):
        lx = cx - lw // 2
        lx = max(12, min(w - lw - 12, lx))
        ldraw.text(
            (lx + shadow_offset, curr_y + shadow_offset),
            ln,
            font=font,
            fill=shadow_color,
            stroke_width=stroke_w,
            stroke_fill=shadow_color,
        )
        ldraw.text(
            (lx, curr_y),
            ln,
            font=font,
            fill=fill_color,
            stroke_width=stroke_w,
            stroke_fill=stroke_color,
        )
        curr_y += lh + line_gap

    canvas_rgba.alpha_composite(layer)
    return (x1, y1, x2, y2)


def render_typography(
    proj_dir: str | Path,
    item_or_id: dict[str, Any] | str,
    overrides: Optional[dict[str, Any]] = None,
    save_project_file: bool = True,
) -> dict[str, Any]:
    """
    非破坏性文字、署名、电话贴纸与景深文字 (`depth_text`) 渲染引擎：
    - 始终从干净的 `raw/<id>.png` 读取底图，绝不污染原图；
    - 当 `auto_avoid_face=True` 时，基于 `item["faces"]` 自动调整 `title_y` / `subtitle_y` / `sticker_y`，确保不遮挡人脸；
    - 当 `depth_text=True` 时，自动确保前景抠图 `matted/<id>_fg.png` 存在，先将主标题放大 `1.35x` 绘制在背景层，再叠回前景人物图层，最后在顶层绘制副标题、贴纸与 AI 署名；
    - 输出合成图至 `composed/<id>_final.png`。
    """
    p = ensure_project_dirs(proj_dir)
    if isinstance(item_or_id, str):
        data = load_project(p)
        item = _find_item(data, item_or_id)
    else:
        data = None
        item = item_or_id

    typo = dict(DEFAULT_TYPOGRAPHY)
    typo.update(item.get("typography") or {})
    if overrides:
        typo.update(overrides)

    raw_abs = p / item["raw_file"]
    if not raw_abs.is_file():
        raise FileNotFoundError(f"原图文件不存在: {raw_abs}")

    if not item.get("faces") and typo.get("auto_avoid_face", True):
        insp = detect_faces_and_qc(raw_abs, expected_aspect=item.get("aspect", ""))
        item["faces"] = insp["faces"]
        item["qc"] = insp["qc"]

    if typo.get("auto_avoid_face", True):
        typo = solve_face_safe_typography(typo, item.get("faces") or [])
        item.setdefault("qc", {})["face_overlap"] = False

    item["typography"] = typo

    base_rgba = Image.open(raw_abs).convert("RGBA")
    w, h = base_rgba.size
    preset_name = str(typo.get("preset") or "cinema_gold")
    preset_cfg = TYPO_PRESETS.get(preset_name, TYPO_PRESETS["cinema_gold"])

    title_str = str(typo.get("title") or "").strip()
    sub_str = str(typo.get("subtitle") or "").strip()
    sig_str = str(typo.get("signature") or "").strip()
    sticker_path_str = str(typo.get("sticker_path") or "").strip()

    if typo.get("enabled", True):
        base_title_px = int(round(min(w, h) * 0.068 * float(typo.get("title_scale") or 1.0)))
        if typo.get("depth_text", False) and title_str:
            # 景深穿插文字：确保前景层存在 -> 绘制 1.35x 大标题 -> 叠加前景人物
            matted_rel = item.get("matted_file") or ""
            matted_abs = (p / matted_rel) if matted_rel else None
            if not (matted_abs and matted_abs.is_file()):
                matte_res = matte_item(p, item["id"], mode="rmbg", prefer_fast=True, save_project_file=False, _item_ref=item)
                matted_abs = Path(matte_res["matted_path"]) if matte_res.get("matted_path") else None

            depth_title_px = int(round(base_title_px * 1.35))
            _draw_styled_text_block(
                base_rgba,
                title_str,
                float(typo.get("title_x") or 0.5),
                float(typo.get("title_y") or 0.18),
                depth_title_px,
                preset_cfg,
                is_subtitle=False,
            )
            if matted_abs and matted_abs.is_file():
                fg_rgba = Image.open(matted_abs).convert("RGBA")
                if fg_rgba.size != (w, h):
                    fg_rgba = fg_rgba.resize((w, h), Image.Resampling.LANCZOS)
                base_rgba.alpha_composite(fg_rgba)
        elif title_str:
            _draw_styled_text_block(
                base_rgba,
                title_str,
                float(typo.get("title_x") or 0.5),
                float(typo.get("title_y") or 0.12),
                base_title_px,
                preset_cfg,
                is_subtitle=False,
            )

        if sub_str:
            sub_px = max(18, int(round(min(w, h) * 0.038)))
            _draw_styled_text_block(
                base_rgba,
                sub_str,
                float(typo.get("subtitle_x") or 0.5),
                float(typo.get("subtitle_y") or 0.20),
                sub_px,
                preset_cfg,
                is_subtitle=True,
            )

        # 叠加电话贴纸 / PNG 徽标
        if sticker_path_str and Path(sticker_path_str).is_file():
            try:
                st_im = Image.open(sticker_path_str).convert("RGBA")
                target_st_w = int(round(w * 0.68 * float(typo.get("sticker_scale") or 0.85)))
                scale_f = target_st_w / float(max(1, st_im.width))
                target_st_h = max(16, int(round(st_im.height * scale_f)))
                st_im = st_im.resize(( max(16, target_st_w), target_st_h ), Image.Resampling.LANCZOS)
                sx = int(round(float(typo.get("sticker_x") or 0.5) * w)) - st_im.width // 2
                sy = int(round(float(typo.get("sticker_y") or 0.82) * h)) - st_im.height // 2
                sx = max(8, min(w - st_im.width - 8, sx))
                sy = max(8, min(h - st_im.height - 8, sy))
                base_rgba.alpha_composite(st_im, dest=(sx, sy))
            except Exception as exc:
                log.warning("贴纸渲染失败 (%s): %s", sticker_path_str, exc)

        # 底部 AI 署名覆层 (如 `.   Generated by AI #xy`)
        if sig_str:
            sig_px = max(14, int(round(min(w, h) * 0.024)))
            sig_font = _load_font(sig_px, bold=False)
            sig_layer = Image.new("RGBA", (w, h), (0, 0, 0, 0))
            sdraw = ImageDraw.Draw(sig_layer)
            sb = sdraw.textbbox((0, 0), sig_str, font=sig_font)
            sw, sh = sb[2] - sb[0], sb[3] - sb[1]
            sx = int(round(float(typo.get("sig_x") or 0.5) * w)) - sw // 2
            sy = int(round(float(typo.get("sig_y") or 0.94) * h)) - sh // 2
            sx = max(10, min(w - sw - 10, sx))
            sy = max(10, min(h - sh - 10, sy))
            sdraw.text(
                (sx, sy),
                sig_str,
                font=sig_font,
                fill=(255, 255, 255, 195),
                stroke_width=1,
                stroke_fill=(0, 0, 0, 175),
            )
            base_rgba.alpha_composite(sig_layer)

    comp_rel = item.get("composed_file") or f"composed/{item['id']}_final.png"
    item["composed_file"] = comp_rel
    comp_abs = p / comp_rel
    comp_abs.parent.mkdir(parents=True, exist_ok=True)
    base_rgba.convert("RGB").save(comp_abs, format="PNG")
    item["mtime"] = _now_ms()

    if save_project_file and data is not None:
        save_project(p, data)

    return {
        "ok": True,
        "item_id": item["id"],
        "composed_file": comp_rel,
        "composed_path": str(comp_abs),
        "typography": item["typography"],
        "qc": item.get("qc", {}),
    }


